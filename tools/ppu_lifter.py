# ---------------------------------------------------------------------------
# Instruction -> C translation
# ---------------------------------------------------------------------------

def _parse_operands(operands: str) -> list[str]:
    """Split operands string by commas, stripping whitespace."""
    return [o.strip() for o in operands.split(",") if o.strip()]


def _reg_idx(token: str) -> str:
    """Extract register index from 'r3' -> '3', 'f5' -> '5', 'v2' -> '2'."""
    m = re.match(r"[rfv](\d+)", token)
    return m.group(1) if m else token


def _disp_base(token: str):
    """Parse 'disp(rN)' -> (disp_str, N)."""
    m = re.match(r"(-?0x[0-9A-Fa-f]+|[0-9-]+)\(r(\d+)\)", token)
    if m:
        disp = m.group(1)
        base = m.group(2)
        return disp, base
    return None, None


def _imm(token: str) -> str:
    """Return a C literal for an immediate value token."""
    token = token.strip()
    if token.startswith("0x") or token.startswith("-0x"):
        return token
    try:
        v = int(token)
        if v < 0:
            return str(v)
        return f"0x{v:X}" if v > 9 else str(v)
    except ValueError:
        return token


def _cr_field_set(bf: int) -> str:
    """Generate C to set a CR field from a comparison result."""
    shift = (7 - bf) * 4
    return (f"ctx->cr = (ctx->cr & ~(0xFu << {shift})) | "
            f"(cr_val << {shift})")


@dataclass
class LiftedFunction:
    """A single lifted C function."""
    name: str = ""
    start_addr: int = 0
    end_addr: int = 0
    body_lines: list[str] = field(default_factory=list)
    calls: list[int] = field(default_factory=list)  # addresses of bl targets
    # bctr address -> sorted list of distinct in-function switch-case targets
    # (recovered GCC jump tables; emitted as a switch instead of an indirect call)
    jump_tables: dict = field(default_factory=dict)


class PPULifter:
    """Translates PPU instructions into C source."""

    def __init__(self):
        self.source_base = "ppu_recomp"
        self.functions: list[LiftedFunction] = []
        self.call_targets: set[int] = set()
        self.branch_targets: set[int] = set()  # all func_X references (b/bc trampolines)
        self.module_toc: int = 0            # r2 base; needed to resolve jump-table bases
        self.word_at: dict[int, int] = {}   # guest addr -> raw BE word (for reading tables)
        # addr(int) -> recovered name label (from Ghidra analysis). Emitted as a
        # comment above func_ADDR so dispatch stays address-based.
        self.name_map: dict[int, str] = {}

    def lift_function(self, instructions: list[Instruction],
                      start: int, end: int) -> LiftedFunction:
        """Lift a range of instructions into a C function."""
        func = LiftedFunction(
            name=f"func_{start:08X}",
            start_addr=start,
            end_addr=end,
        )

        # Collect branch targets within the function for labels
        internal_targets: set[int] = set()
        for insn in instructions:
            if insn.addr < start or insn.addr >= end:
                continue
            if insn.mnemonic.startswith("b") and insn.mnemonic not in (
                    "blr", "bctr", "bctrl", "bl", "blrl"):
                ops = _parse_operands(insn.operands)
                for op in ops:
                    if op.startswith("0x"):
                        try:
                            target = int(op, 16)
                            if start <= target < end:
                                internal_targets.add(target)
                        except ValueError:
                            pass

        # Recover GCC switch jump tables (computed bctr) into explicit case
        # targets, so a dispatch that lands mid-function becomes a local goto
        # instead of an unresolved indirect call. Their targets are in-function
        # addresses and must get loc_ labels.
        finsns = sorted((i for i in instructions if start <= i.addr < end),
                        key=lambda x: x.addr)
        func.jump_tables = self._recover_jump_tables(finsns, start, end)
        for tgts in func.jump_tables.values():
            internal_targets.update(tgts)

        for insn in instructions:
            if insn.addr < start or insn.addr >= end:
                continue

            # Label
            if insn.addr in internal_targets:
                func.body_lines.append(f"loc_{insn.addr:08X}:")

            c_line = self._translate(insn, func)
            if c_line:
                func.body_lines.append(f"    {c_line}")

        self.functions.append(func)
        return func

    # ------------------------------------------------------------------ #
    # Jump-table (switch) recovery
    # ------------------------------------------------------------------ #
    @staticmethod
    def _reg(tok: str):
        m = re.match(r"^r(\d+)$", tok.strip())
        return int(m.group(1)) if m else None

    def _reg_value(self, finsns, before_idx, reg, depth=3):
        """Return the guest address/value held in `reg` just before
        finsns[before_idx], by following TOC-relative load chains (r2 == the
        module TOC). Handles both the direct form `lwz rB, D(r2)` and the
        indirect form `lwz rB, D2(rX)` where rX itself comes from the TOC
        (a TOC entry that points to a struct holding the jump table). Returns
        None if `reg` isn't a simple load chain."""
        if reg == 2:
            return self.module_toc
        if depth < 0:
            return None
        for k in range(before_idx - 1, max(before_idx - 1 - 24, -1), -1):
            ins = finsns[k]
            parts = [p.strip() for p in ins.operands.split(",", 1)]
            if len(parts) != 2 or self._reg(parts[0]) != reg:
                continue
            if ins.mnemonic not in ("lwz", "ld"):
                return None  # reg redefined by a non-load
            m = re.match(r"(-?0x[0-9A-Fa-f]+|-?\d+)\((r\d+)\)$", parts[1])
            if not m:
                return None
            disp = int(m.group(1), 0)
            base = self._reg(m.group(2))
            base_val = self._reg_value(finsns, k, base, depth - 1)
            if base_val is None:
                return None
            return self.word_at.get((base_val + disp) & 0xFFFFFFFF)
        return None

    def _recover_jump_tables(self, finsns, fstart, fend):
        """Detect the GCC switch dispatch
            lwz rB,DISP(r2); ...; lwzx rO,rIdx,rB; extsw rO; add rT,rO,rB;
            mtctr rT; bctr
        and read the offset table (target = tableBase + sext(entry)). Returns
        {bctr_addr: [distinct in-function targets]}."""
        out = {}
        if not self.module_toc or not self.word_at:
            return out
        for i, insn in enumerate(finsns):
            if insn.mnemonic != "bctr":
                continue
            # mtctr rT just before
            rT = None
            for k in range(i - 1, max(i - 4, -1), -1):
                if finsns[k].mnemonic == "mtctr":
                    rT = self._reg(finsns[k].operands.split(",")[0]); break
            if rT is None:
                continue
            # add rT, rOff, rBase feeding ctr; rBase holds the jump-table base
            # address (resolved through the TOC load chain).
            tbl = None
            for k in range(i - 2, max(i - 9, -1), -1):
                ins2 = finsns[k]
                if ins2.mnemonic not in ("add", "add."):
                    continue
                parts = [p.strip() for p in ins2.operands.split(",")]
                if len(parts) != 3 or self._reg(parts[0]) != rT:
                    continue
                for cand in (self._reg(parts[2]), self._reg(parts[1])):
                    if cand is None:
                        continue
                    v = self._reg_value(finsns, k, cand)
                    if v is not None:
                        tbl = v; break
                break
            if tbl is None:
                continue
            targets, seen = [], set()
            for n in range(0, 8192):
                off = self.word_at.get((tbl + 4 * n) & 0xFFFFFFFF)
                if off is None:
                    break
                soff = off - 0x100000000 if (off & 0x80000000) else off
                tgt = (tbl + soff) & 0xFFFFFFFF
                if not (fstart <= tgt < fend):
                    break
                targets.append(tgt); seen.add(tgt)
            if len(targets) >= 2:
                out[insn.addr] = sorted(seen)
        return out

    # ------------------------------------------------------------------ #
    # Per-instruction translation
    # ------------------------------------------------------------------ #

    def _translate(self, insn: Instruction, func: LiftedFunction) -> str:
        """Translate one Instruction to a C statement string."""
        mn = insn.mnemonic
        ops = _parse_operands(insn.operands)
        addr = insn.addr

        # ------- Arithmetic -------
        if mn == "li":
            rd = _reg_idx(ops[0])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)({_imm(ops[1])});"

        if mn == "lis":
            rd = _reg_idx(ops[0])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)((uint32_t){_imm(ops[1])} << 16);"

        if mn == "addi":
            rd, ra = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)(ctx->gpr[{ra}] + {_imm(ops[2])});"

        if mn == "addis":
            rd, ra = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)(ctx->gpr[{ra}] + ((uint32_t){_imm(ops[2])} << 16));"

        if mn == "addic" or mn == "addic.":
            rd, ra = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)(ctx->gpr[{ra}] + {_imm(ops[2])});"

        if mn in ("add", "add.", "addo", "addo."):
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)((uint32_t)ctx->gpr[{ra}] + (uint32_t)ctx->gpr[{rb}]);"

        if mn in ("subf", "subf.", "subfo"):
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)((uint32_t)ctx->gpr[{rb}] - (uint32_t)ctx->gpr[{ra}]);"

        if mn == "subfic":
            rd, ra = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)({_imm(ops[2])} - (int32_t)ctx->gpr[{ra}]);"

        if mn in ("neg", "neg."):
            rd, ra = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)(-(int32_t)ctx->gpr[{ra}]);"

        if mn == "mulli":
            rd, ra = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)((int32_t)ctx->gpr[{ra}] * {_imm(ops[2])});"

        if mn in ("mullw", "mullw."):
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)((int32_t)ctx->gpr[{ra}] * (int32_t)ctx->gpr[{rb}]);"

        if mn in ("mulhw", "mulhw."):
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)((int32_t)((int64_t)(int32_t)ctx->gpr[{ra}] * (int64_t)(int32_t)ctx->gpr[{rb}] >> 32));"

        if mn in ("mulhwu", "mulhwu."):
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)((int32_t)((uint64_t)(uint32_t)ctx->gpr[{ra}] * (uint64_t)(uint32_t)ctx->gpr[{rb}] >> 32));"

        if mn in ("divw", "divw."):
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)((int32_t)ctx->gpr[{ra}] / (int32_t)ctx->gpr[{rb}]);"

        if mn in ("divwu", "divwu."):
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)((uint32_t)ctx->gpr[{ra}] / (uint32_t)ctx->gpr[{rb}]);"

        # ------- Logical -------
        if mn == "ori":
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{ra}] = ctx->gpr[{rs}] | {_imm(ops[2])};"

        if mn == "oris":
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{ra}] = ctx->gpr[{rs}] | ((uint64_t){_imm(ops[2])} << 16);"

        if mn == "xori":
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{ra}] = ctx->gpr[{rs}] ^ {_imm(ops[2])};"

        if mn == "xoris":
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{ra}] = ctx->gpr[{rs}] ^ ((uint64_t){_imm(ops[2])} << 16);"

        if mn in ("andi.", "andis."):
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            shift = " << 16" if mn == "andis." else ""
            return f"ctx->gpr[{ra}] = ctx->gpr[{rs}] & ((uint64_t){_imm(ops[2])}{shift});"

        if mn == "nop":
            return "/* nop */;"

        for log_mn, c_op in [("and", "&"), ("or", "|"), ("xor", "^")]:
            if mn == log_mn or mn == log_mn + ".":
                ra, rs, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
                return f"ctx->gpr[{ra}] = ctx->gpr[{rs}] {c_op} ctx->gpr[{rb}];"

        if mn in ("nand", "nand."):
            ra, rs, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{ra}] = ~(ctx->gpr[{rs}] & ctx->gpr[{rb}]);"

        if mn in ("nor", "nor."):
            ra, rs, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{ra}] = ~(ctx->gpr[{rs}] | ctx->gpr[{rb}]);"

        if mn in ("andc", "andc."):
            ra, rs, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{ra}] = ctx->gpr[{rs}] & ~ctx->gpr[{rb}];"

        if mn in ("orc", "orc."):
            ra, rs, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{ra}] = ctx->gpr[{rs}] | ~ctx->gpr[{rb}];"

        if mn in ("extsb", "extsb."):
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{ra}] = (int64_t)(int8_t)ctx->gpr[{rs}];"

        if mn in ("extsh", "extsh."):
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{ra}] = (int64_t)(int16_t)ctx->gpr[{rs}];"

        if mn in ("extsw", "extsw."):
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{ra}] = (int64_t)(int32_t)ctx->gpr[{rs}];"

        if mn in ("cntlzw", "cntlzw."):
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{ra}] = __builtin_clz((uint32_t)ctx->gpr[{rs}]);"

        # ------- Shift / Rotate -------
        if mn.startswith("rlwinm"):
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            sh, mb, me = ops[2], ops[3], ops[4]
            return (f"ctx->gpr[{ra}] = (int64_t)(int32_t)"
                    f"ppc_rlwinm((uint32_t)ctx->gpr[{rs}], {sh}, {mb}, {me});")

        if mn.startswith("rlwimi"):
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            sh, mb, me = ops[2], ops[3], ops[4]
            return (f"ctx->gpr[{ra}] = (int64_t)(int32_t)"
                    f"ppc_rlwimi((uint32_t)ctx->gpr[{ra}], (uint32_t)ctx->gpr[{rs}], {sh}, {mb}, {me});")

        if mn in ("slw", "slw."):
            ra, rs, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{ra}] = (int64_t)(int32_t)((uint32_t)ctx->gpr[{rs}] << (ctx->gpr[{rb}] & 0x3F));"

        if mn in ("srw", "srw."):
            ra, rs, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{ra}] = (int64_t)(int32_t)((uint32_t)ctx->gpr[{rs}] >> (ctx->gpr[{rb}] & 0x3F));"

        if mn in ("sraw", "sraw."):
            ra, rs, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{ra}] = (int64_t)(int32_t)((int32_t)ctx->gpr[{rs}] >> (ctx->gpr[{rb}] & 0x3F));"

        if mn in ("srawi", "srawi."):
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{ra}] = (int64_t)(int32_t)((int32_t)ctx->gpr[{rs}] >> {_imm(ops[2])});"

        # ------- 64-bit Rotate / Shift -------
        if mn.startswith("rldicl"):
            # rldicl rA, rS, sh, mb  -- rotate left dword then clear left
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            sh, mb = int(ops[2]), int(ops[3])
            return (f"ctx->gpr[{ra}] = ppc_rldicl(ctx->gpr[{rs}], {sh}, {mb});")

        if mn.startswith("rldicr"):
            # rldicr rA, rS, sh, me  -- rotate left dword then clear right
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            sh, me = int(ops[2]), int(ops[3])
            return (f"ctx->gpr[{ra}] = ppc_rldicr(ctx->gpr[{rs}], {sh}, {me});")

        if mn.startswith("rldic") and not mn.startswith("rldicl") and not mn.startswith("rldicr"):
            # rldic rA, rS, sh, mb
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            sh, mb = int(ops[2]), int(ops[3])
            return (f"ctx->gpr[{ra}] = ppc_rldic(ctx->gpr[{rs}], {sh}, {mb});")

        if mn.startswith("rldcl"):
            # rldcl rA, rS, rB, mb — rotate left dword then clear left (register shift)
            ra, rs, rb_r = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            mb = int(ops[3])
            return (f"ctx->gpr[{ra}] = ppc_rldicl(ctx->gpr[{rs}], (int)(ctx->gpr[{rb_r}] & 63), {mb});")

        if mn.startswith("rldcr"):
            # rldcr rA, rS, rB, me — rotate left dword then clear right (register shift)
            ra, rs, rb_r = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            me = int(ops[3])
            return (f"ctx->gpr[{ra}] = ppc_rldicr(ctx->gpr[{rs}], (int)(ctx->gpr[{rb_r}] & 63), {me});")

        if mn.startswith("rldimi"):
            # rldimi rA, rS, sh, mb  -- rotate left dword then insert mask
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            sh, mb = int(ops[2]), int(ops[3])
            return (f"ctx->gpr[{ra}] = ppc_rldimi(ctx->gpr[{ra}], ctx->gpr[{rs}], {sh}, {mb});")

        # 64-bit shifts
        if mn in ("sld", "sld."):
            ra, rs, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{ra}] = (ctx->gpr[{rb}] & 64) ? 0 : (ctx->gpr[{rs}] << (ctx->gpr[{rb}] & 63));"

        if mn in ("srd", "srd."):
            ra, rs, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{ra}] = (ctx->gpr[{rb}] & 64) ? 0 : (ctx->gpr[{rs}] >> (ctx->gpr[{rb}] & 63));"

        if mn in ("srad", "srad."):
            ra, rs, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{ra}] = (uint64_t)((int64_t)ctx->gpr[{rs}] >> (ctx->gpr[{rb}] & 63));"

        if mn in ("sradi", "sradi."):
            ra, rs = _reg_idx(ops[0]), _reg_idx(ops[1])
            return f"ctx->gpr[{ra}] = (uint64_t)((int64_t)ctx->gpr[{rs}] >> {_imm(ops[2])});"

        # ------- Loads -------
        load_map = {
            "lbz": ("vm_read8", False), "lbzu": ("vm_read8", False),
            "lhz": ("vm_read16", False), "lhzu": ("vm_read16", False),
            "lha": ("vm_read16", True), "lhau": ("vm_read16", True),
            "lwz": ("vm_read32", False), "lwzu": ("vm_read32", False),
            "ld": ("vm_read64", False), "ldu": ("vm_read64", False),
        }
        if mn in load_map:
            helper, signed = load_map[mn]
            rd_i = _reg_idx(ops[0])
            disp, base = _disp_base(ops[1])
            if disp is not None:
                expr = f"{helper}(ctx->gpr[{base}] + {disp})"
                if signed and "16" in helper:
                    expr = f"(int64_t)(int16_t){expr}"
                return f"ctx->gpr[{rd_i}] = {expr};"
            return f"/* {mn} unhandled operands: {insn.operands} */;"

        # ------- Stores -------
        store_map = {
            "stb": "vm_write8", "stbu": "vm_write8",
            "sth": "vm_write16", "sthu": "vm_write16",
            "stw": "vm_write32", "stwu": "vm_write32",
            "std": "vm_write64", "stdu": "vm_write64",
        }
        if mn in store_map:
            helper = store_map[mn]
            rs_i = _reg_idx(ops[0])
            disp, base = _disp_base(ops[1])
            if disp is not None:
                line = f"{helper}(ctx->gpr[{base}] + {disp}, ctx->gpr[{rs_i}]);"
                # Handle update forms
                if mn.endswith("u"):
                    line += f" ctx->gpr[{base}] += {disp};"
                return line
            return f"/* {mn} unhandled operands: {insn.operands} */;"

        # ------- Indexed Loads -------
        idx_load_map = {
            "lbzx": "vm_read8", "lhzx": "vm_read16", "lwzx": "vm_read32", "ldx": "vm_read64",
            "lhax": "vm_read16", "lwax": "vm_read32",
            "lbzux": "vm_read8", "lhzux": "vm_read16", "lwzux": "vm_read32",
        }
        if mn in idx_load_map:
            helper = idx_load_map[mn]
            rd_i, ra_i, rb_i = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            ea = f"(ctx->gpr[{ra_i}] + ctx->gpr[{rb_i}])" if ra_i != "0" else f"ctx->gpr[{rb_i}]"
            expr = f"{helper}({ea})"
            if mn in ("lhax", "lwax"):
                cast = "(int16_t)" if "h" in mn else "(int32_t)"
                expr = f"(int64_t){cast}{expr}"
            return f"ctx->gpr[{rd_i}] = {expr};"

        if mn == "lwa":
            rd_i = _reg_idx(ops[0])
            disp, base = _disp_base(ops[1])
            if disp is not None:
                return f"ctx->gpr[{rd_i}] = (int64_t)(int32_t)vm_read32(ctx->gpr[{base}] + {disp});"

        # ------- Indexed Stores -------
        idx_store_map = {
            "stbx": "vm_write8", "sthx": "vm_write16", "stwx": "vm_write32", "stdx": "vm_write64",
            "stbux": "vm_write8", "sthux": "vm_write16", "stwux": "vm_write32",
        }
        if mn in idx_store_map:
            helper = idx_store_map[mn]
            rs_i, ra_i, rb_i = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            ea = f"(ctx->gpr[{ra_i}] + ctx->gpr[{rb_i}])" if ra_i != "0" else f"ctx->gpr[{rb_i}]"
            return f"{helper}({ea}, ctx->gpr[{rs_i}]);"

        # ------- Indexed FP Loads/Stores -------
        if mn in ("lfsx", "lfdx"):
            frd, ra_i, rb_i = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            ea = f"(ctx->gpr[{ra_i}] + ctx->gpr[{rb_i}])" if ra_i != "0" else f"ctx->gpr[{rb_i}]"
            if "s" in mn:
                return f"{{ uint32_t tmp = vm_read32({ea}); float ftmp; memcpy(&ftmp, &tmp, 4); ctx->fpr[{frd}] = ftmp; }}"
            else:
                return f"{{ uint64_t tmp = vm_read64({ea}); memcpy(&ctx->fpr[{frd}], &tmp, 8); }}"

        if mn in ("stfsx", "stfdx"):
            frs, ra_i, rb_i = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            ea = f"(ctx->gpr[{ra_i}] + ctx->gpr[{rb_i}])" if ra_i != "0" else f"ctx->gpr[{rb_i}]"
            if "s" in mn:
                return f"{{ float ftmp = (float)ctx->fpr[{frs}]; uint32_t tmp; memcpy(&tmp, &ftmp, 4); vm_write32({ea}, tmp); }}"
            else:
                return f"{{ uint64_t tmp; memcpy(&tmp, &ctx->fpr[{frs}], 8); vm_write64({ea}, tmp); }}"

        # ------- Compare -------
        if mn in ("cmpwi", "cmpdi"):
            # ops: [crN,] rA, imm  or  rA, imm
            if ops[0].startswith("cr"):
                bf = int(ops[0][2:])
                ra_i = _reg_idx(ops[1])
                imm = _imm(ops[2])
            else:
                bf = 0
                ra_i = _reg_idx(ops[0])
                imm = _imm(ops[1])
            cast = "(int32_t)" if mn == "cmpwi" else "(int64_t)"
            shift = (7 - bf) * 4
            return (f"{{ int64_t a = {cast}ctx->gpr[{ra_i}]; int64_t b = (int64_t){imm}; "
                    f"uint32_t cr_val = (a < b) ? 8 : (a > b) ? 4 : 2; "
                    f"ctx->cr = (ctx->cr & ~(0xFu << {shift})) | (cr_val << {shift}); }}")

        if mn in ("cmplwi", "cmpldi"):
            if ops[0].startswith("cr"):
                bf = int(ops[0][2:])
                ra_i = _reg_idx(ops[1])
                imm = _imm(ops[2])
            else:
                bf = 0
                ra_i = _reg_idx(ops[0])
                imm = _imm(ops[1])
            cast = "(uint32_t)" if mn == "cmplwi" else "(uint64_t)"
            shift = (7 - bf) * 4
            return (f"{{ uint64_t a = {cast}ctx->gpr[{ra_i}]; uint64_t b = (uint64_t){imm}; "
                    f"uint32_t cr_val = (a < b) ? 8 : (a > b) ? 4 : 2; "
                    f"ctx->cr = (ctx->cr & ~(0xFu << {shift})) | (cr_val << {shift}); }}")

        if mn in ("cmpw", "cmpd"):
            if ops[0].startswith("cr"):
                bf = int(ops[0][2:])
                ra_i = _reg_idx(ops[1])
                rb_i = _reg_idx(ops[2])
            else:
                bf = 0
                ra_i = _reg_idx(ops[0])
                rb_i = _reg_idx(ops[1])
            cast = "(int32_t)" if mn == "cmpw" else "(int64_t)"
            shift = (7 - bf) * 4
            return (f"{{ int64_t a = {cast}ctx->gpr[{ra_i}]; int64_t b = {cast}ctx->gpr[{rb_i}]; "
                    f"uint32_t cr_val = (a < b) ? 8 : (a > b) ? 4 : 2; "
                    f"ctx->cr = (ctx->cr & ~(0xFu << {shift})) | (cr_val << {shift}); }}")

        if mn in ("cmplw", "cmpld"):
            if ops[0].startswith("cr"):
                bf = int(ops[0][2:])
                ra_i = _reg_idx(ops[1])
                rb_i = _reg_idx(ops[2])
            else:
                bf = 0
                ra_i = _reg_idx(ops[0])
                rb_i = _reg_idx(ops[1])
            cast = "(uint32_t)" if mn == "cmplw" else "(uint64_t)"
            shift = (7 - bf) * 4
            return (f"{{ uint64_t a = {cast}ctx->gpr[{ra_i}]; uint64_t b = {cast}ctx->gpr[{rb_i}]; "
                    f"uint32_t cr_val = (a < b) ? 8 : (a > b) ? 4 : 2; "
                    f"ctx->cr = (ctx->cr & ~(0xFu << {shift})) | (cr_val << {shift}); }}")

        # ------- Branches -------
        if mn == "blr" or mn == "blrl":
            return "return;"

        if mn == "b":
            target = ops[0]
            try:
                tgt = int(target, 16)
                if func.start_addr <= tgt < func.end_addr:
                    return f"goto loc_{tgt:08X};"
                else:
                    # Use trampoline for cross-fragment branches to avoid
                    # stack-growing recursion when backward branches re-enter
                    # a fragment's prologue (stack allocation).
                    self.branch_targets.add(tgt)
                    return f"{{ g_trampoline_fn = (void(*)(void*))func_{tgt:08X}; return; }}"
            except ValueError:
                return f"goto {target}; /* branch */"

        if mn == "bl":
            target = ops[0]
            try:
                tgt = int(target, 16)
                func.calls.append(tgt)
                self.call_targets.add(tgt)
                return f"func_{tgt:08X}(ctx); DRAIN_TRAMPOLINE(ctx);"
            except ValueError:
                return f"/* bl {target} */;"

        # Conditional return: b<cond>lr [cr]
        # Examples: beqlr, bnelr, bltlr, blelr, bgtlr, bgelr, bdnzlr, bdzlr
        # These branch to LR (i.e. return from the function) when the
        # condition holds. Previously these fell through to the generic
        # branch handler and were emitted as /* blelr cr7 */; no-ops — a
        # huge bug, since any memcpy/memset/str* variant that used an early
        # conditional return silently turned into an infinite tail loop.
        if (mn.endswith("lr") and mn not in ("bl", "blr", "blrl") and
                mn.startswith("b") and
                not mn.startswith("blr")):  # guard against "blr" literal
            cond = self._branch_condition(mn, ops)
            return f"if ({cond}) return;"

        # Conditional indirect call/return through CTR: b<cond>ctr [cr]
        # Used by vtable dispatch with a predicate.
        if (mn.endswith("ctr") and mn not in ("bctr", "bctrl") and
                mn.startswith("b")):
            cond = self._branch_condition(mn, ops)
            return f"if ({cond}) {{ ps3_indirect_call(ctx); DRAIN_TRAMPOLINE(ctx); return; }}"

        # Conditional branches
        if mn.startswith("b") and mn not in ("bl", "b", "blr", "bctr", "bctrl"):
            # Try to extract target from last operand
            target_str = ops[-1] if ops else ""
            try:
                tgt = int(target_str, 16)
                if func.start_addr <= tgt < func.end_addr:
                    cond = self._branch_condition(mn, ops)
                    return f"if ({cond}) goto loc_{tgt:08X};"
                else:
                    cond = self._branch_condition(mn, ops)
                    # Use trampoline for cross-fragment conditional branches
                    self.branch_targets.add(tgt)
                    return f"if ({cond}) {{ g_trampoline_fn = (void(*)(void*))func_{tgt:08X}; return; }}"
            except ValueError:
                return f"/* {mn} {insn.operands} */;"

        if mn == "bctr":
            targets = func.jump_tables.get(insn.addr)
            if targets:
                cases = " ".join(
                    f"case 0x{t:08X}u: goto loc_{t:08X};" for t in targets)
                return ("switch ((uint32_t)ctx->ctr) { " + cases +
                        " default: ps3_indirect_call(ctx); return; }")
            return "ps3_indirect_call(ctx); return;"

        if mn == "bctrl":
            # Indirect call through CTR register. The CTR value is a GUEST
            # address (or OPD pointer). We dispatch through a hash table
            # that maps guest addresses to host function pointers.
            return "ps3_indirect_call(ctx); DRAIN_TRAMPOLINE(ctx);"

        # ------- SPR -------
        if mn == "mflr":
            rd_i = _reg_idx(ops[0])
            return f"ctx->gpr[{rd_i}] = ctx->lr;"

        if mn == "mtlr":
            rs_i = _reg_idx(ops[0])
            return f"ctx->lr = ctx->gpr[{rs_i}];"

        if mn == "mfctr":
            rd_i = _reg_idx(ops[0])
            return f"ctx->gpr[{rd_i}] = ctx->ctr;"

        if mn == "mtctr":
            rs_i = _reg_idx(ops[0])
            # Mask CTR to 32 bits — PS3 games use 32-bit loop counts.
            # Without masking, sign-extended 64-bit values from addi/rldicr
            # produce CTR values like 0x9FFFFFFFE0000000 causing infinite loops.
            return f"ctx->ctr = (uint32_t)ctx->gpr[{rs_i}];"

        if mn == "mfcr":
            rd_i = _reg_idx(ops[0])
            return f"ctx->gpr[{rd_i}] = ctx->cr;"

        if mn in ("mtcr", "mtcrf"):
            return f"ctx->cr = (uint32_t)ctx->gpr[{_reg_idx(ops[-1])}];"

        # ------- Syscall -------
        if mn == "sc":
            return "lv2_syscall(ctx);"

        # ------- Floating-point loads/stores -------
        if mn in ("lfs", "lfsu", "lfd", "lfdu"):
            frd = _reg_idx(ops[0])
            disp, base = _disp_base(ops[1])
            if disp is not None:
                if "s" in mn:
                    return (f"{{ uint32_t tmp = vm_read32(ctx->gpr[{base}] + {disp}); "
                            f"float ftmp; memcpy(&ftmp, &tmp, 4); ctx->fpr[{frd}] = ftmp; }}")
                else:
                    return (f"{{ uint64_t tmp = vm_read64(ctx->gpr[{base}] + {disp}); "
                            f"memcpy(&ctx->fpr[{frd}], &tmp, 8); }}")

        if mn in ("stfs", "stfsu", "stfd", "stfdu"):
            frs = _reg_idx(ops[0])
            disp, base = _disp_base(ops[1])
            if disp is not None:
                if "s" in mn:
                    return (f"{{ float ftmp = (float)ctx->fpr[{frs}]; uint32_t tmp; "
                            f"memcpy(&tmp, &ftmp, 4); vm_write32(ctx->gpr[{base}] + {disp}, tmp); }}")
                else:
                    return (f"{{ uint64_t tmp; memcpy(&tmp, &ctx->fpr[{frs}], 8); "
                            f"vm_write64(ctx->gpr[{base}] + {disp}, tmp); }}")

        # ------- FP arithmetic -------
        fp_binary = {
            "fadd": "+", "fadds": "+", "fsub": "-", "fsubs": "-",
            "fmul": "*", "fmuls": "*", "fdiv": "/", "fdivs": "/",
        }
        mn_base = mn.rstrip(".")
        if mn_base in fp_binary:
            frd = _reg_idx(ops[0])
            fra = _reg_idx(ops[1])
            frb = _reg_idx(ops[2])
            op_c = fp_binary[mn_base]
            return f"ctx->fpr[{frd}] = ctx->fpr[{fra}] {op_c} ctx->fpr[{frb}];"

        if mn_base in ("fmr",):
            frd = _reg_idx(ops[0])
            frb = _reg_idx(ops[1])
            return f"ctx->fpr[{frd}] = ctx->fpr[{frb}];"

        if mn_base in ("fneg",):
            frd = _reg_idx(ops[0])
            frb = _reg_idx(ops[1])
            return f"ctx->fpr[{frd}] = -ctx->fpr[{frb}];"

        if mn_base in ("fabs",):
            frd = _reg_idx(ops[0])
            frb = _reg_idx(ops[1])
            return f"ctx->fpr[{frd}] = fabs(ctx->fpr[{frb}]);"

        if mn_base in ("fnabs",):
            frd = _reg_idx(ops[0])
            frb = _reg_idx(ops[1])
            return f"ctx->fpr[{frd}] = -fabs(ctx->fpr[{frb}]);"

        if mn_base in ("fmadd", "fmadds"):
            frd, fra, frc, frb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2]), _reg_idx(ops[3])
            return f"ctx->fpr[{frd}] = ctx->fpr[{fra}] * ctx->fpr[{frc}] + ctx->fpr[{frb}];"

        if mn_base in ("fmsub", "fmsubs"):
            frd, fra, frc, frb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2]), _reg_idx(ops[3])
            return f"ctx->fpr[{frd}] = ctx->fpr[{fra}] * ctx->fpr[{frc}] - ctx->fpr[{frb}];"

        if mn_base in ("fnmadd", "fnmadds"):
            frd, fra, frc, frb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2]), _reg_idx(ops[3])
            return f"ctx->fpr[{frd}] = -(ctx->fpr[{fra}] * ctx->fpr[{frc}] + ctx->fpr[{frb}]);"

        if mn_base in ("fnmsub", "fnmsubs"):
            frd, fra, frc, frb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2]), _reg_idx(ops[3])
            return f"ctx->fpr[{frd}] = -(ctx->fpr[{fra}] * ctx->fpr[{frc}] - ctx->fpr[{frb}]);"

        if mn_base in ("frsp",):
            frd = _reg_idx(ops[0])
            frb = _reg_idx(ops[1])
            return f"ctx->fpr[{frd}] = (float)ctx->fpr[{frb}];"

        if mn_base in ("fctiwz",):
            frd = _reg_idx(ops[0])
            frb = _reg_idx(ops[1])
            return (f"{{ int32_t iv = (int32_t)ctx->fpr[{frb}]; uint64_t tmp; "
                    f"memcpy(&tmp, &ctx->fpr[{frd}], 8); "
                    f"tmp = (tmp & 0xFFFFFFFF00000000ULL) | (uint32_t)iv; "
                    f"memcpy(&ctx->fpr[{frd}], &tmp, 8); }}")

        if mn_base in ("fctid", "fctidz"):
            frd = _reg_idx(ops[0])
            frb = _reg_idx(ops[1])
            return (f"{{ int64_t iv = (int64_t)ctx->fpr[{frb}]; "
                    f"memcpy(&ctx->fpr[{frd}], &iv, 8); }}")

        if mn_base in ("fcfid",):
            frd = _reg_idx(ops[0])
            frb = _reg_idx(ops[1])
            return (f"{{ int64_t iv; memcpy(&iv, &ctx->fpr[{frb}], 8); "
                    f"ctx->fpr[{frd}] = (double)iv; }}")

        if mn_base == "fsqrt" or mn_base == "fsqrts":
            frd = _reg_idx(ops[0])
            frb = _reg_idx(ops[1])
            return f"ctx->fpr[{frd}] = sqrt(ctx->fpr[{frb}]);"

        if mn_base == "fsel":
            frd, fra, frc, frb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2]), _reg_idx(ops[3])
            return f"ctx->fpr[{frd}] = (ctx->fpr[{fra}] >= 0.0) ? ctx->fpr[{frc}] : ctx->fpr[{frb}];"

        # ------- FP compare -------
        if mn_base == "fcmpu" or mn_base == "fcmpo":
            if ops[0].startswith("cr"):
                bf = int(ops[0][2:])
                fra = _reg_idx(ops[1])
                frb = _reg_idx(ops[2])
            else:
                bf = 0
                fra = _reg_idx(ops[0])
                frb = _reg_idx(ops[1])
            shift = (7 - bf) * 4
            return (f"{{ double a = ctx->fpr[{fra}]; double b = ctx->fpr[{frb}]; "
                    f"uint32_t cr_val = (a < b) ? 8 : (a > b) ? 4 : 2; "
                    f"ctx->cr = (ctx->cr & ~(0xFu << {shift})) | (cr_val << {shift}); }}")

        # ------- 64-bit multiply / divide -------
        if mn == "mulld":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{rd}] = (int64_t)ctx->gpr[{ra}] * (int64_t)ctx->gpr[{rb}];"

        if mn == "mullw":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return f"ctx->gpr[{rd}] = (int64_t)(int32_t)((int32_t)ctx->gpr[{ra}] * (int32_t)ctx->gpr[{rb}]);"

        if mn == "divd":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"ctx->gpr[{rd}] = (ctx->gpr[{rb}] != 0) ? "
                    f"(int64_t)ctx->gpr[{ra}] / (int64_t)ctx->gpr[{rb}] : 0;")

        if mn == "divdu":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"ctx->gpr[{rd}] = (ctx->gpr[{rb}] != 0) ? "
                    f"ctx->gpr[{ra}] / ctx->gpr[{rb}] : 0;")

        # ------- Add/subtract extended (with carry) -------
        if mn == "adde":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ca = (ctx->xer >> 29) & 1; "
                    f"uint64_t result = ctx->gpr[{ra}] + ctx->gpr[{rb}] + ca; "
                    f"ctx->xer = (ctx->xer & ~(1u << 29)) | "
                    f"((result < ctx->gpr[{ra}] || (ca && result == ctx->gpr[{ra}])) ? (1u << 29) : 0); "
                    f"ctx->gpr[{rd}] = result; }}")

        if mn == "addze":
            rd, ra = _reg_idx(ops[0]), _reg_idx(ops[1])
            return (f"{{ uint64_t ca = (ctx->xer >> 29) & 1; "
                    f"uint64_t result = ctx->gpr[{ra}] + ca; "
                    f"ctx->xer = (ctx->xer & ~(1u << 29)) | "
                    f"((result < ctx->gpr[{ra}]) ? (1u << 29) : 0); "
                    f"ctx->gpr[{rd}] = result; }}")

        if mn == "subfe":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ca = (ctx->xer >> 29) & 1; "
                    f"uint64_t result = ~ctx->gpr[{ra}] + ctx->gpr[{rb}] + ca; "
                    f"ctx->xer = (ctx->xer & ~(1u << 29)) | "
                    f"((result <= ctx->gpr[{rb}] && ca) ? (1u << 29) : 0); "
                    f"ctx->gpr[{rd}] = result; }}")

        # ------- Condition register logical ops -------
        if mn == "cror":
            bt, ba, bb = int(ops[0]), int(ops[1]), int(ops[2])
            return (f"{{ uint32_t a = (ctx->cr >> (31 - {ba})) & 1; "
                    f"uint32_t b = (ctx->cr >> (31 - {bb})) & 1; "
                    f"ctx->cr = (ctx->cr & ~(1u << (31 - {bt}))) | ((a | b) << (31 - {bt})); }}")

        if mn == "crand":
            bt, ba, bb = int(ops[0]), int(ops[1]), int(ops[2])
            return (f"{{ uint32_t a = (ctx->cr >> (31 - {ba})) & 1; "
                    f"uint32_t b = (ctx->cr >> (31 - {bb})) & 1; "
                    f"ctx->cr = (ctx->cr & ~(1u << (31 - {bt}))) | ((a & b) << (31 - {bt})); }}")

        if mn == "crnand":
            bt, ba, bb = int(ops[0]), int(ops[1]), int(ops[2])
            return (f"{{ uint32_t a = (ctx->cr >> (31 - {ba})) & 1; "
                    f"uint32_t b = (ctx->cr >> (31 - {bb})) & 1; "
                    f"ctx->cr = (ctx->cr & ~(1u << (31 - {bt}))) | ((~(a & b) & 1) << (31 - {bt})); }}")

        if mn == "crxor":
            bt, ba, bb = int(ops[0]), int(ops[1]), int(ops[2])
            return (f"{{ uint32_t a = (ctx->cr >> (31 - {ba})) & 1; "
                    f"uint32_t b = (ctx->cr >> (31 - {bb})) & 1; "
                    f"ctx->cr = (ctx->cr & ~(1u << (31 - {bt}))) | ((a ^ b) << (31 - {bt})); }}")

        if mn == "crnor":
            bt, ba, bb = int(ops[0]), int(ops[1]), int(ops[2])
            return (f"{{ uint32_t a = (ctx->cr >> (31 - {ba})) & 1; "
                    f"uint32_t b = (ctx->cr >> (31 - {bb})) & 1; "
                    f"ctx->cr = (ctx->cr & ~(1u << (31 - {bt}))) | ((~(a | b) & 1) << (31 - {bt})); }}")

        if mn == "creqv":
            bt, ba, bb = int(ops[0]), int(ops[1]), int(ops[2])
            return (f"{{ uint32_t a = (ctx->cr >> (31 - {ba})) & 1; "
                    f"uint32_t b = (ctx->cr >> (31 - {bb})) & 1; "
                    f"ctx->cr = (ctx->cr & ~(1u << (31 - {bt}))) | ((~(a ^ b) & 1) << (31 - {bt})); }}")

        if mn == "crorc":
            bt, ba, bb = int(ops[0]), int(ops[1]), int(ops[2])
            return (f"{{ uint32_t a = (ctx->cr >> (31 - {ba})) & 1; "
                    f"uint32_t b = (ctx->cr >> (31 - {bb})) & 1; "
                    f"ctx->cr = (ctx->cr & ~(1u << (31 - {bt}))) | ((a | (~b & 1)) << (31 - {bt})); }}")

        if mn == "crandc":
            bt, ba, bb = int(ops[0]), int(ops[1]), int(ops[2])
            return (f"{{ uint32_t a = (ctx->cr >> (31 - {ba})) & 1; "
                    f"uint32_t b = (ctx->cr >> (31 - {bb})) & 1; "
                    f"ctx->cr = (ctx->cr & ~(1u << (31 - {bt}))) | ((a & (~b & 1)) << (31 - {bt})); }}")

        # mcrf — move condition register field
        if mn == "mcrf":
            # mcrf crD, crS — copy 4-bit CR field
            bf = int(ops[0][2:]) if ops[0].startswith("cr") else int(ops[0])
            bfa = int(ops[1][2:]) if ops[1].startswith("cr") else int(ops[1])
            dst_shift = (7 - bf) * 4
            src_shift = (7 - bfa) * 4
            return (f"{{ uint32_t field = (ctx->cr >> {src_shift}) & 0xF; "
                    f"ctx->cr = (ctx->cr & ~(0xFu << {dst_shift})) | (field << {dst_shift}); }}")

        # rlwnm — rotate left word then AND with mask (register shift)
        if mn.startswith("rlwnm"):
            ra = _reg_idx(ops[0])
            rs = _reg_idx(ops[1])
            rb = _reg_idx(ops[2])
            mb = int(ops[3])
            me = int(ops[4])
            return f"ctx->gpr[{ra}] = ppc_rlwinm((uint32_t)ctx->gpr[{rs}], (int)(ctx->gpr[{rb}] & 31), {mb}, {me});"

        # mffs — move from FPSCR
        if mn == "mffs" or mn == "mffs.":
            frd = _reg_idx(ops[0])
            return f"{{ uint64_t fpscr64 = ctx->fpscr; memcpy(&ctx->fpr[{frd}], &fpscr64, 8); }}"

        # mtfsf — move to FPSCR fields
        if mn == "mtfsf":
            return f"/* mtfsf: FPSCR update — ignored for now */;"

        # ------- Store/load with update indexed -------
        if mn == "stdux":
            rs, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"vm_write64(ea, ctx->gpr[{rs}]); ctx->gpr[{ra}] = ea; }}")

        if mn == "stwux":
            rs, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"vm_write32(ea, (uint32_t)ctx->gpr[{rs}]); ctx->gpr[{ra}] = ea; }}")

        if mn == "ldux":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"ctx->gpr[{rd}] = vm_read64(ea); ctx->gpr[{ra}] = ea; }}")

        if mn == "lwzux":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"ctx->gpr[{rd}] = vm_read32(ea); ctx->gpr[{ra}] = ea; }}")

        # ------- Atomic load/store with reservation -------
        if mn == "lwarx":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"ctx->gpr[{rd}] = vm_read32(ea); "
                    f"ctx->reserve_addr = (uint32_t)ea; ctx->reserve_value = ctx->gpr[{rd}]; }}")

        if mn == "stwcx" or mn == "stwcx.":
            rs, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"if (ctx->reserve_addr == (uint32_t)ea) {{ "
                    f"vm_write32(ea, (uint32_t)ctx->gpr[{rs}]); "
                    f"ctx->cr = (ctx->cr & ~(0xFu << 28)) | (2u << 28); "  # CR0 = EQ
                    f"}} else {{ "
                    f"ctx->cr = (ctx->cr & ~(0xFu << 28)); "  # CR0 = 0
                    f"}} ctx->reserve_addr = 0; }}")

        if mn == "ldarx":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"ctx->gpr[{rd}] = vm_read64(ea); "
                    f"ctx->reserve_addr = (uint32_t)ea; ctx->reserve_value = ctx->gpr[{rd}]; }}")

        if mn == "stdcx" or mn == "stdcx.":
            rs, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"if (ctx->reserve_addr == (uint32_t)ea) {{ "
                    f"vm_write64(ea, ctx->gpr[{rs}]); "
                    f"ctx->cr = (ctx->cr & ~(0xFu << 28)) | (2u << 28); "
                    f"}} else {{ "
                    f"ctx->cr = (ctx->cr & ~(0xFu << 28)); "
                    f"}} ctx->reserve_addr = 0; }}")

        # ------- Trap (tw) — used for assertions, safe to no-op in recomp -------
        if mn == "tw" or mn == "twi" or mn == "td" or mn == "tdi":
            return f"/* trap: {mn} {insn.operands} — ignored */;"

        # ------- Byte-reverse loads/stores -------
        if mn == "lwbrx":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"uint32_t raw; memcpy(&raw, vm_base + (uint32_t)ea, 4); "
                    f"ctx->gpr[{rd}] = raw; }}") # NOTE: no bswap — reads in host (LE) order

        if mn == "stwbrx":
            rs, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"uint32_t raw = (uint32_t)ctx->gpr[{rs}]; "
                    f"memcpy(vm_base + (uint32_t)ea, &raw, 4); }}")

        if mn == "lhbrx":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"uint16_t raw; memcpy(&raw, vm_base + (uint32_t)ea, 2); "
                    f"ctx->gpr[{rd}] = raw; }}")

        if mn == "sthbrx":
            rs, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"uint16_t raw = (uint16_t)ctx->gpr[{rs}]; "
                    f"memcpy(vm_base + (uint32_t)ea, &raw, 2); }}")

        # ------- Load algebraic -------
        if mn == "lwax":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"ctx->gpr[{rd}] = (int64_t)(int32_t)vm_read32(ea); }}")

        if mn == "lhaux":
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"ctx->gpr[{rd}] = (int64_t)(int16_t)vm_read16(ea); ctx->gpr[{ra}] = ea; }}")

        # ------- Move from time base -------
        if mn == "mftb":
            rd = _reg_idx(ops[0])
            return (f"{{ static uint64_t tb = 79800000ULL; tb += 16667; "
                    f"ctx->gpr[{rd}] = tb; }}")

        if mn == "mftbu":
            rd = _reg_idx(ops[0])
            return (f"{{ static uint64_t tb = 79800000ULL; tb += 16667; "
                    f"ctx->gpr[{rd}] = (tb >> 32); }}")

        # ------- Cache/sync ops (safe to no-op) -------
        # dcbz zeros a 128-byte cache line — MUST be implemented, not no-oped!
        # Games use dcbz loops to zero large memory regions. If we no-op dcbz,
        # the loop runs trillions of iterations doing nothing.
        if mn == "dcbz":
            ra = _reg_idx(ops[0])
            rb = _reg_idx(ops[1])
            return (f"{{ uint64_t ea = (ctx->gpr[{ra}] + ctx->gpr[{rb}]) & ~0x7FULL; "
                    f"memset(vm_base + (uint32_t)ea, 0, 128); }}")

        if mn in ("dcbt", "dcbtst", "dcbf", "dcbst", "dcba", "icbi",
                  "sync", "eieio", "isync", "lwsync", "ptesync"):
            return f"/* {mn}: cache/sync — no-op */;"

        # ------- addme/subfme/subfze (carry arithmetic, 2-op) -------
        if mn.startswith("addme"):
            rd, ra = _reg_idx(ops[0]), _reg_idx(ops[1])
            return (f"{{ uint64_t ca = (ctx->xer >> 29) & 1; "
                    f"uint64_t result = ctx->gpr[{ra}] + ca - 1; "
                    f"ctx->xer = (ctx->xer & ~(1u << 29)) | "
                    f"((result >= ctx->gpr[{ra}]) ? (1u << 29) : 0); "
                    f"ctx->gpr[{rd}] = result; }}")

        if mn.startswith("subfme"):
            rd, ra = _reg_idx(ops[0]), _reg_idx(ops[1])
            return (f"{{ uint64_t ca = (ctx->xer >> 29) & 1; "
                    f"uint64_t result = ~ctx->gpr[{ra}] + ca - 1; "
                    f"ctx->gpr[{rd}] = result; }}")

        if mn.startswith("subfze"):
            rd, ra = _reg_idx(ops[0]), _reg_idx(ops[1])
            return (f"{{ uint64_t ca = (ctx->xer >> 29) & 1; "
                    f"uint64_t result = ~ctx->gpr[{ra}] + ca; "
                    f"ctx->xer = (ctx->xer & ~(1u << 29)) | "
                    f"((ca && result == 0) ? (1u << 29) : 0); "
                    f"ctx->gpr[{rd}] = result; }}")

        # ------- mulhd / mulhdu (multiply high doubleword) -------
        if mn.startswith("mulhd") and not mn.startswith("mulhdu"):
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"ctx->gpr[{rd}] = (uint64_t)ppc_mulhd("
                    f"(int64_t)ctx->gpr[{ra}], (int64_t)ctx->gpr[{rb}]);")

        if mn.startswith("mulhdu"):
            rd, ra, rb = _reg_idx(ops[0]), _reg_idx(ops[1]), _reg_idx(ops[2])
            return (f"ctx->gpr[{rd}] = (uint64_t)ppc_mulhdu("
                    f"ctx->gpr[{ra}], ctx->gpr[{rb}]);")

        # ------- VMX/AltiVec vector load/store -------
        # These are the foundation for all SIMD code. Vector registers
        # are 128-bit (ctx->vr[N], type u128 or uint8_t[16]).
        if mn == "lvx":
            vd = int(ops[0][1:]) if ops[0].startswith("v") else _reg_idx(ops[0])
            ra = _reg_idx(ops[1])
            rb = _reg_idx(ops[2])
            return (f"{{ uint64_t ea = (ctx->gpr[{ra}] + ctx->gpr[{rb}]) & ~0xFULL; "
                    f"memcpy(&ctx->vr[{vd}], vm_base + (uint32_t)ea, 16); }}")

        if mn == "stvx":
            vs = int(ops[0][1:]) if ops[0].startswith("v") else _reg_idx(ops[0])
            ra = _reg_idx(ops[1])
            rb = _reg_idx(ops[2])
            return (f"{{ uint64_t ea = (ctx->gpr[{ra}] + ctx->gpr[{rb}]) & ~0xFULL; "
                    f"memcpy(vm_base + (uint32_t)ea, &ctx->vr[{vs}], 16); }}")

        if mn == "lvebx" or mn == "lvehx" or mn == "lvewx":
            vd = int(ops[0][1:]) if ops[0].startswith("v") else _reg_idx(ops[0])
            ra = _reg_idx(ops[1])
            rb = _reg_idx(ops[2])
            # These load a single element into the vector register.
            # For simplicity, zero the register and load at the element position.
            size = {"lvebx": 1, "lvehx": 2, "lvewx": 4}[mn]
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"memset(&ctx->vr[{vd}], 0, 16); "
                    f"memcpy(&ctx->vr[{vd}], vm_base + (uint32_t)ea, {size}); }}")

        if mn == "stvebx" or mn == "stvehx" or mn == "stvewx":
            vs = int(ops[0][1:]) if ops[0].startswith("v") else _reg_idx(ops[0])
            ra = _reg_idx(ops[1])
            rb = _reg_idx(ops[2])
            size = {"stvebx": 1, "stvehx": 2, "stvewx": 4}[mn]
            return (f"{{ uint64_t ea = ctx->gpr[{ra}] + ctx->gpr[{rb}]; "
                    f"memcpy(vm_base + (uint32_t)ea, &ctx->vr[{vs}], {size}); }}")

        if mn == "lvsl" or mn == "lvsr":
            vd = int(ops[0][1:]) if ops[0].startswith("v") else _reg_idx(ops[0])
            ra = _reg_idx(ops[1])
            rb = _reg_idx(ops[2])
            # lvsl/lvsr generate permutation vectors for unaligned loads.
            # lvsl: for byte offset b, generates {b, b+1, b+2, ..., b+15}
            # lvsr: generates {16-b, 17-b, ..., 31-b}
            if mn == "lvsl":
                return (f"{{ uint8_t b = (uint8_t)((ctx->gpr[{ra}] + ctx->gpr[{rb}]) & 0xF); "
                        f"for (int i = 0; i < 16; i++) ((uint8_t*)&ctx->vr[{vd}])[i] = b + i; }}")
            else:
                return (f"{{ uint8_t b = (uint8_t)(16 - ((ctx->gpr[{ra}] + ctx->gpr[{rb}]) & 0xF)); "
                        f"for (int i = 0; i < 16; i++) ((uint8_t*)&ctx->vr[{vd}])[i] = b + i; }}")

        # VMX permute (vperm) — critical for unaligned loads
        if mn == "vperm":
            vd = int(ops[0][1:])
            va = int(ops[1][1:])
            vb = int(ops[2][1:])
            vc = int(ops[3][1:])
            return (f"{{ uint8_t* a = (uint8_t*)&ctx->vr[{va}]; "
                    f"uint8_t* b = (uint8_t*)&ctx->vr[{vb}]; "
                    f"uint8_t* c = (uint8_t*)&ctx->vr[{vc}]; "
                    f"uint8_t* d = (uint8_t*)&ctx->vr[{vd}]; "
                    f"uint8_t tmp[16]; "
                    f"for (int i = 0; i < 16; i++) {{ "
                    f"uint8_t sel = c[i] & 0x1F; "
                    f"tmp[i] = (sel < 16) ? a[sel] : b[sel - 16]; }} "
                    f"memcpy(d, tmp, 16); }}")

        # VMX splat (vspltw, vsplth, vspltb) — duplicate one element across vector
        if mn == "vspltw":
            vd = int(ops[0][1:])
            vb = int(ops[1][1:])
            uimm = int(ops[2]) & 3
            return (f"{{ uint32_t* d = (uint32_t*)&ctx->vr[{vd}]; "
                    f"uint32_t val = ((uint32_t*)&ctx->vr[{vb}])[{uimm}]; "
                    f"d[0] = d[1] = d[2] = d[3] = val; }}")

        if mn == "vxor":
            vd = int(ops[0][1:])
            va = int(ops[1][1:])
            vb = int(ops[2][1:])
            return (f"{{ uint64_t* d = (uint64_t*)&ctx->vr[{vd}]; "
                    f"uint64_t* a = (uint64_t*)&ctx->vr[{va}]; "
                    f"uint64_t* b = (uint64_t*)&ctx->vr[{vb}]; "
                    f"d[0] = a[0] ^ b[0]; d[1] = a[1] ^ b[1]; }}")

        if mn == "vor":
            vd = int(ops[0][1:])
            va = int(ops[1][1:])
            vb = int(ops[2][1:])
            return (f"{{ uint64_t* d = (uint64_t*)&ctx->vr[{vd}]; "
                    f"uint64_t* a = (uint64_t*)&ctx->vr[{va}]; "
                    f"uint64_t* b = (uint64_t*)&ctx->vr[{vb}]; "
                    f"d[0] = a[0] | b[0]; d[1] = a[1] | b[1]; }}")

        if mn == "vand":
            vd = int(ops[0][1:])
            va = int(ops[1][1:])
            vb = int(ops[2][1:])
            return (f"{{ uint64_t* d = (uint64_t*)&ctx->vr[{vd}]; "
                    f"uint64_t* a = (uint64_t*)&ctx->vr[{va}]; "
                    f"uint64_t* b = (uint64_t*)&ctx->vr[{vb}]; "
                    f"d[0] = a[0] & b[0]; d[1] = a[1] & b[1]; }}")

        if mn == "vandc":  # vand with complement: vD = vA & ~vB
            vd = int(ops[0][1:])
            va = int(ops[1][1:])
            vb = int(ops[2][1:])
            return (f"{{ uint64_t* d = (uint64_t*)&ctx->vr[{vd}]; "
                    f"uint64_t* a = (uint64_t*)&ctx->vr[{va}]; "
                    f"uint64_t* b = (uint64_t*)&ctx->vr[{vb}]; "
                    f"d[0] = a[0] & ~b[0]; d[1] = a[1] & ~b[1]; }}")

        # ------- VMX floating-point arithmetic -------
        if mn == "vmaddfp":
            # Vector Multiply-Add Floating-Point: vD = vA * vC + vB
            vd = int(ops[0][1:])
            va = int(ops[1][1:])
            vb = int(ops[2][1:])  # Note: vmaddfp operand order is vD, vA, vC, vB
            vc = int(ops[3][1:])
            return (f"{{ float* d = (float*)&ctx->vr[{vd}]; "
                    f"float* a = (float*)&ctx->vr[{va}]; "
                    f"float* b = (float*)&ctx->vr[{vb}]; "
                    f"float* c = (float*)&ctx->vr[{vc}]; "
                    f"d[0]=a[0]*c[0]+b[0]; d[1]=a[1]*c[1]+b[1]; "
                    f"d[2]=a[2]*c[2]+b[2]; d[3]=a[3]*c[3]+b[3]; }}")

        if mn == "vnmsubfp":
            # Vector Negative Multiply-Subtract: vD = -(vA * vC - vB) = vB - vA*vC
            vd = int(ops[0][1:])
            va = int(ops[1][1:])
            vb = int(ops[2][1:])
            vc = int(ops[3][1:])
            return (f"{{ float* d = (float*)&ctx->vr[{vd}]; "
                    f"float* a = (float*)&ctx->vr[{va}]; "
                    f"float* b = (float*)&ctx->vr[{vb}]; "
                    f"float* c = (float*)&ctx->vr[{vc}]; "
                    f"d[0]=b[0]-a[0]*c[0]; d[1]=b[1]-a[1]*c[1]; "
                    f"d[2]=b[2]-a[2]*c[2]; d[3]=b[3]-a[3]*c[3]; }}")

        if mn == "vaddfp":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ float* d=(float*)&ctx->vr[{vd}]; float* a=(float*)&ctx->vr[{va}]; "
                    f"float* b=(float*)&ctx->vr[{vb}]; "
                    f"d[0]=a[0]+b[0]; d[1]=a[1]+b[1]; d[2]=a[2]+b[2]; d[3]=a[3]+b[3]; }}")

        if mn == "vsubfp":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ float* d=(float*)&ctx->vr[{vd}]; float* a=(float*)&ctx->vr[{va}]; "
                    f"float* b=(float*)&ctx->vr[{vb}]; "
                    f"d[0]=a[0]-b[0]; d[1]=a[1]-b[1]; d[2]=a[2]-b[2]; d[3]=a[3]-b[3]; }}")

        if mn == "vmulfp":
            # Not a real PPC instruction but some disassemblers emit it
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ float* d=(float*)&ctx->vr[{vd}]; float* a=(float*)&ctx->vr[{va}]; "
                    f"float* b=(float*)&ctx->vr[{vb}]; "
                    f"d[0]=a[0]*b[0]; d[1]=a[1]*b[1]; d[2]=a[2]*b[2]; d[3]=a[3]*b[3]; }}")

        # VMX select (vsel) — bitwise select: vD = (vA & ~vC) | (vB & vC)
        if mn == "vsel":
            vd = int(ops[0][1:])
            va = int(ops[1][1:])
            vb = int(ops[2][1:])
            vc = int(ops[3][1:])
            return (f"{{ uint64_t* d=(uint64_t*)&ctx->vr[{vd}]; "
                    f"uint64_t* a=(uint64_t*)&ctx->vr[{va}]; "
                    f"uint64_t* b=(uint64_t*)&ctx->vr[{vb}]; "
                    f"uint64_t* c=(uint64_t*)&ctx->vr[{vc}]; "
                    f"d[0]=(a[0]&~c[0])|(b[0]&c[0]); d[1]=(a[1]&~c[1])|(b[1]&c[1]); }}")

        # VMX compare (vcmpequw, vcmpeqfp, vcmpgefp, vcmpgtfp)
        if mn.startswith("vcmpeqfp"):
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ float* a=(float*)&ctx->vr[{va}]; float* b=(float*)&ctx->vr[{vb}]; "
                    f"uint32_t* d=(uint32_t*)&ctx->vr[{vd}]; "
                    f"d[0]=a[0]==b[0]?~0u:0; d[1]=a[1]==b[1]?~0u:0; "
                    f"d[2]=a[2]==b[2]?~0u:0; d[3]=a[3]==b[3]?~0u:0; }}")

        if mn.startswith("vcmpgefp"):
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ float* a=(float*)&ctx->vr[{va}]; float* b=(float*)&ctx->vr[{vb}]; "
                    f"uint32_t* d=(uint32_t*)&ctx->vr[{vd}]; "
                    f"d[0]=a[0]>=b[0]?~0u:0; d[1]=a[1]>=b[1]?~0u:0; "
                    f"d[2]=a[2]>=b[2]?~0u:0; d[3]=a[3]>=b[3]?~0u:0; }}")

        if mn.startswith("vcmpgtfp"):
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ float* a=(float*)&ctx->vr[{va}]; float* b=(float*)&ctx->vr[{vb}]; "
                    f"uint32_t* d=(uint32_t*)&ctx->vr[{vd}]; "
                    f"d[0]=a[0]>b[0]?~0u:0; d[1]=a[1]>b[1]?~0u:0; "
                    f"d[2]=a[2]>b[2]?~0u:0; d[3]=a[3]>b[3]?~0u:0; }}")

        # VMX shift (vsldoi) — shift left double by octet immediate
        if mn == "vsldoi":
            vd = int(ops[0][1:])
            va = int(ops[1][1:])
            vb = int(ops[2][1:])
            sh = int(ops[3])  # numeric shift count (disasm emits plain number)
            return (f"{{ uint8_t tmp[32]; "
                    f"memcpy(tmp, &ctx->vr[{va}], 16); memcpy(tmp+16, &ctx->vr[{vb}], 16); "
                    f"memcpy(&ctx->vr[{vd}], tmp + {sh}, 16); }}")

        # VMX integer multiply-accumulate
        if mn == "vmsumshm":
            # vmsumshm vD, vA, vB, vC: multiply s16×s16 pairs, add to s32 accumulator
            vd = int(ops[0][1:])
            va = int(ops[1][1:])
            vb = int(ops[2][1:])
            vc = int(ops[3][1:])
            return (f"{{ int16_t* a=(int16_t*)&ctx->vr[{va}]; "
                    f"int16_t* b=(int16_t*)&ctx->vr[{vb}]; "
                    f"int32_t* c=(int32_t*)&ctx->vr[{vc}]; "
                    f"int32_t* d=(int32_t*)&ctx->vr[{vd}]; "
                    f"for(int i=0;i<4;i++) d[i]=c[i]+(int32_t)a[i*2]*(int32_t)b[i*2]+(int32_t)a[i*2+1]*(int32_t)b[i*2+1]; }}")

        # VMX integer compare
        if mn.startswith("vcmpequh"):
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint16_t* a=(uint16_t*)&ctx->vr[{va}]; uint16_t* b=(uint16_t*)&ctx->vr[{vb}]; "
                    f"uint16_t* d=(uint16_t*)&ctx->vr[{vd}]; "
                    f"for(int i=0;i<8;i++) d[i]=a[i]==b[i]?(uint16_t)~0:0; }}")

        if mn.startswith("vcmpequw"):
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint32_t* a=(uint32_t*)&ctx->vr[{va}]; uint32_t* b=(uint32_t*)&ctx->vr[{vb}]; "
                    f"uint32_t* d=(uint32_t*)&ctx->vr[{vd}]; "
                    f"for(int i=0;i<4;i++) d[i]=a[i]==b[i]?~0u:0; }}")

        # ------- VMX integer arithmetic (generated from disasm decode table) -------
        # These are simple per-element operations on vector registers.

        # Integer add/sub (unsigned byte/halfword/word modulo)
        vmx_int_binop = {
            "vaddubm": ("uint8_t",  16, "+"), "vadduhm": ("uint16_t", 8, "+"),
            "vadduwm": ("uint32_t", 4,  "+"),
            "vsububm": ("uint8_t",  16, "-"), "vsubuhm": ("uint16_t", 8, "-"),
            "vsubuwm": ("uint32_t", 4,  "-"),
            "vand":    ("uint64_t", 2,  "&"), "vandc":   None, # special
            "vnor":    None, # special
            "vmaxub":  None, "vmaxuh": None, "vmaxuw": None,
            "vminub":  None, "vminuh": None, "vminuw": None,
            "vmaxsb":  None, "vmaxsh": None, "vmaxsw": None,
            "vminsb":  None, "vminsh": None, "vminsw": None,
        }

        if mn in ("vaddubm", "vadduhm", "vadduwm", "vsububm", "vsubuhm", "vsubuwm"):
            ty, cnt, op = vmx_int_binop[mn]
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ {ty}* d=({ty}*)&ctx->vr[{vd}]; {ty}* a=({ty}*)&ctx->vr[{va}]; "
                    f"{ty}* b=({ty}*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<{cnt};i++) d[i]=a[i]{op}b[i]; }}")

        if mn == "vandc":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint64_t* d=(uint64_t*)&ctx->vr[{vd}]; "
                    f"uint64_t* a=(uint64_t*)&ctx->vr[{va}]; "
                    f"uint64_t* b=(uint64_t*)&ctx->vr[{vb}]; "
                    f"d[0]=a[0]&~b[0]; d[1]=a[1]&~b[1]; }}")

        if mn == "vnor":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint64_t* d=(uint64_t*)&ctx->vr[{vd}]; "
                    f"uint64_t* a=(uint64_t*)&ctx->vr[{va}]; "
                    f"uint64_t* b=(uint64_t*)&ctx->vr[{vb}]; "
                    f"d[0]=~(a[0]|b[0]); d[1]=~(a[1]|b[1]); }}")

        # Integer min/max
        for prefix in ("vmax", "vmin"):
            for suffix, ty, cnt, signed in [("ub","uint8_t",16,0),("uh","uint16_t",8,0),
                                             ("uw","uint32_t",4,0),("sb","int8_t",16,1),
                                             ("sh","int16_t",8,1),("sw","int32_t",4,1)]:
                iname = prefix + suffix
                if mn == iname:
                    vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
                    cmp = ">" if prefix == "vmax" else "<"
                    return (f"{{ {ty}* d=({ty}*)&ctx->vr[{vd}]; {ty}* a=({ty}*)&ctx->vr[{va}]; "
                            f"{ty}* b=({ty}*)&ctx->vr[{vb}]; "
                            f"for(int i=0;i<{cnt};i++) d[i]=a[i]{cmp}b[i]?a[i]:b[i]; }}")

        # Float min/max
        if mn == "vmaxfp" or mn == "vminfp":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            cmp = ">" if mn == "vmaxfp" else "<"
            return (f"{{ float* d=(float*)&ctx->vr[{vd}]; float* a=(float*)&ctx->vr[{va}]; "
                    f"float* b=(float*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<4;i++) d[i]=a[i]{cmp}b[i]?a[i]:b[i]; }}")

        # Splat immediate (vspltisb/h/w) — splat a 5-bit signed immediate
        if mn in ("vspltisb", "vspltish", "vspltisw"):
            vd = int(ops[0][1:])
            simm = int(ops[1]) if not ops[1].startswith("v") else int(ops[1][1:])
            # Sign extend 5-bit to appropriate type
            if simm > 15: simm -= 32
            if mn == "vspltisb":
                return (f"{{ memset(&ctx->vr[{vd}], (uint8_t){simm}, 16); }}")
            elif mn == "vspltish":
                return (f"{{ int16_t* d=(int16_t*)&ctx->vr[{vd}]; "
                        f"for(int i=0;i<8;i++) d[i]={simm}; }}")
            else:
                return (f"{{ int32_t* d=(int32_t*)&ctx->vr[{vd}]; "
                        f"for(int i=0;i<4;i++) d[i]={simm}; }}")

        # Merge (vmrghb/h/w, vmrglb/h/w) — interleave elements
        if mn.startswith("vmrg"):
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            high = "h" in mn[4:5]
            if "b" in mn[4:]:
                ty, cnt = "uint8_t", 16
            elif "h" in mn[4:]:
                ty, cnt = "uint16_t", 8
            else:
                ty, cnt = "uint32_t", 4
            half = cnt // 2
            off = 0 if high else half
            return (f"{{ {ty} tmp[{cnt}]; {ty}* a=({ty}*)&ctx->vr[{va}]; {ty}* b=({ty}*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<{half};i++) {{ tmp[i*2]=a[{off}+i]; tmp[i*2+1]=b[{off}+i]; }} "
                    f"memcpy(&ctx->vr[{vd}], tmp, 16); }}")

        # Float reciprocal estimate / reciprocal sqrt estimate
        if mn == "vrefp":
            vd, vb = int(ops[0][1:]), int(ops[1][1:]) if len(ops) > 1 else int(ops[0][1:])
            return (f"{{ float* d=(float*)&ctx->vr[{vd}]; float* b=(float*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<4;i++) d[i]=1.0f/b[i]; }}")

        if mn == "vrsqrtefp":
            vd, vb = int(ops[0][1:]), int(ops[1][1:]) if len(ops) > 1 else int(ops[0][1:])
            return (f"{{ float* d=(float*)&ctx->vr[{vd}]; float* b=(float*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<4;i++) d[i]=1.0f/sqrtf(b[i]); }}")

        # Float/int convert (operand form "vD, vB, UIMM" — UIMM is a bare int)
        if mn == "vcfsx" or mn == "vcfux":
            vd, vb = int(ops[0][1:]), int(ops[1][1:])
            uimm = int(ops[2]) if len(ops) > 2 and not ops[2].startswith("v") else 0
            src_ty = "int32_t" if mn == "vcfsx" else "uint32_t"
            scale = f" / {1 << uimm}.0f" if uimm > 0 else ""
            return (f"{{ float* d=(float*)&ctx->vr[{vd}]; {src_ty}* b=({src_ty}*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<4;i++) d[i]=(float)b[i]{scale}; }}")

        if mn == "vctsxs" or mn == "vctuxs":
            vd, vb = int(ops[0][1:]), int(ops[1][1:])
            uimm = int(ops[2]) if len(ops) > 2 and not ops[2].startswith("v") else 0
            dst_ty = "int32_t" if mn == "vctsxs" else "uint32_t"
            scale = f" * {1 << uimm}.0f" if uimm > 0 else ""
            return (f"{{ {dst_ty}* d=({dst_ty}*)&ctx->vr[{vd}]; float* b=(float*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<4;i++) d[i]=({dst_ty})(b[i]{scale}); }}")

        # Compare with Rc (vcmpeqfp., vcmpgefp., etc.)
        if mn.startswith("vcmpbfp"):
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ float* a=(float*)&ctx->vr[{va}]; float* b=(float*)&ctx->vr[{vb}]; "
                    f"uint32_t* d=(uint32_t*)&ctx->vr[{vd}]; "
                    f"for(int i=0;i<4;i++) {{ uint32_t r=0; "
                    f"if(a[i]>b[i]) r|=0x80000000u; if(a[i]<-b[i]) r|=0x40000000u; d[i]=r; }} }}")

        # ------- Additional VMX integer instructions -------
        # Byte compare equal
        if mn.startswith("vcmpequb"):
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint8_t* d=(uint8_t*)&ctx->vr[{vd}]; uint8_t* a=(uint8_t*)&ctx->vr[{va}]; "
                    f"uint8_t* b=(uint8_t*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<16;i++) d[i]=a[i]==b[i]?0xFFu:0u; }}")

        # Saturating add
        if mn == "vaddsbs":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ int8_t* d=(int8_t*)&ctx->vr[{vd}]; int8_t* a=(int8_t*)&ctx->vr[{va}]; "
                    f"int8_t* b=(int8_t*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<16;i++){{int32_t r=(int32_t)a[i]+(int32_t)b[i]; d[i]=(int8_t)(r>127?127:r<-128?-128:r);}} }}")
        if mn == "vadduhs":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint16_t* d=(uint16_t*)&ctx->vr[{vd}]; uint16_t* a=(uint16_t*)&ctx->vr[{va}]; "
                    f"uint16_t* b=(uint16_t*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<8;i++){{uint32_t r=(uint32_t)a[i]+(uint32_t)b[i]; d[i]=(uint16_t)(r>65535u?65535u:r);}} }}")
        if mn == "vaddshs":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ int16_t* d=(int16_t*)&ctx->vr[{vd}]; int16_t* a=(int16_t*)&ctx->vr[{va}]; "
                    f"int16_t* b=(int16_t*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<8;i++){{int32_t r=(int32_t)a[i]+(int32_t)b[i]; d[i]=(int16_t)(r>32767?32767:r<-32768?-32768:r);}} }}")
        if mn == "vadduws":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint32_t* d=(uint32_t*)&ctx->vr[{vd}]; uint32_t* a=(uint32_t*)&ctx->vr[{va}]; "
                    f"uint32_t* b=(uint32_t*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<4;i++){{uint64_t r=(uint64_t)a[i]+(uint64_t)b[i]; d[i]=(uint32_t)(r>0xFFFFFFFFu?0xFFFFFFFFu:r);}} }}")

        # Subtract saturate
        if mn == "vsubsws":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ int32_t* d=(int32_t*)&ctx->vr[{vd}]; int32_t* a=(int32_t*)&ctx->vr[{va}]; "
                    f"int32_t* b=(int32_t*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<4;i++){{int64_t r=(int64_t)a[i]-(int64_t)b[i]; d[i]=(int32_t)(r>0x7FFFFFFFLL?0x7FFFFFFFLL:r<-0x80000000LL?-0x80000000LL:r);}} }}")

        # Shifts and rotates
        if mn == "vslb":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint8_t* d=(uint8_t*)&ctx->vr[{vd}]; uint8_t* a=(uint8_t*)&ctx->vr[{va}]; "
                    f"uint8_t* b=(uint8_t*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<16;i++) d[i]=(uint8_t)(a[i]<<(b[i]&7u)); }}")
        if mn == "vslw":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint32_t* d=(uint32_t*)&ctx->vr[{vd}]; uint32_t* a=(uint32_t*)&ctx->vr[{va}]; "
                    f"uint32_t* b=(uint32_t*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<4;i++) d[i]=a[i]<<(b[i]&31u); }}")
        if mn == "vrlb":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint8_t* d=(uint8_t*)&ctx->vr[{vd}]; uint8_t* a=(uint8_t*)&ctx->vr[{va}]; "
                    f"uint8_t* b=(uint8_t*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<16;i++){{uint8_t s=b[i]&7u; d[i]=(a[i]<<s)|(a[i]>>(8u-s));}} }}")
        if mn == "vrlw":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint32_t* d=(uint32_t*)&ctx->vr[{vd}]; uint32_t* a=(uint32_t*)&ctx->vr[{va}]; "
                    f"uint32_t* b=(uint32_t*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<4;i++){{uint32_t s=b[i]&31u; d[i]=(a[i]<<s)|(a[i]>>(32u-s));}} }}")
        if mn == "vsraw":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ int32_t* d=(int32_t*)&ctx->vr[{vd}]; int32_t* a=(int32_t*)&ctx->vr[{va}]; "
                    f"uint32_t* b=(uint32_t*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<4;i++) d[i]=a[i]>>(b[i]&31u); }}")

        # (vmaxsw handled above by the generic vmax/vmin loop)

        # Integer multiply (odd/even halfword)
        if mn == "vmulouh":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint32_t* d=(uint32_t*)&ctx->vr[{vd}]; uint16_t* a=(uint16_t*)&ctx->vr[{va}]; "
                    f"uint16_t* b=(uint16_t*)&ctx->vr[{vb}]; "
                    f"d[0]=(uint32_t)a[1]*(uint32_t)b[1]; d[1]=(uint32_t)a[3]*(uint32_t)b[3]; "
                    f"d[2]=(uint32_t)a[5]*(uint32_t)b[5]; d[3]=(uint32_t)a[7]*(uint32_t)b[7]; }}")
        if mn == "vmuleuh":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint32_t* d=(uint32_t*)&ctx->vr[{vd}]; uint16_t* a=(uint16_t*)&ctx->vr[{va}]; "
                    f"uint16_t* b=(uint16_t*)&ctx->vr[{vb}]; "
                    f"d[0]=(uint32_t)a[0]*(uint32_t)b[0]; d[1]=(uint32_t)a[2]*(uint32_t)b[2]; "
                    f"d[2]=(uint32_t)a[4]*(uint32_t)b[4]; d[3]=(uint32_t)a[6]*(uint32_t)b[6]; }}")
        if mn == "vmulosh":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ int32_t* d=(int32_t*)&ctx->vr[{vd}]; int16_t* a=(int16_t*)&ctx->vr[{va}]; "
                    f"int16_t* b=(int16_t*)&ctx->vr[{vb}]; "
                    f"d[0]=(int32_t)a[1]*(int32_t)b[1]; d[1]=(int32_t)a[3]*(int32_t)b[3]; "
                    f"d[2]=(int32_t)a[5]*(int32_t)b[5]; d[3]=(int32_t)a[7]*(int32_t)b[7]; }}")

        # Average unsigned byte
        if mn == "vavgub":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ uint8_t* d=(uint8_t*)&ctx->vr[{vd}]; uint8_t* a=(uint8_t*)&ctx->vr[{va}]; "
                    f"uint8_t* b=(uint8_t*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<16;i++) d[i]=(uint8_t)(((unsigned)a[i]+(unsigned)b[i]+1u)>>1); }}")

        # Splat byte (vspltb vD, vB, UIMM — UIMM encoded in vA field)
        # Splat byte/halfword (operand form "vD, vB, UIMM" — UIMM is a bare int,
        # matching the disassembler's vspltb/h/w emission and the vspltw handler).
        if mn == "vspltb":
            vd = int(ops[0][1:]); vb = int(ops[1][1:]); uimm = int(ops[2]) & 15
            return (f"{{ uint8_t* d=(uint8_t*)&ctx->vr[{vd}]; uint8_t* b=(uint8_t*)&ctx->vr[{vb}]; "
                    f"uint8_t v=b[{uimm}]; for(int i=0;i<16;i++) d[i]=v; }}")

        if mn == "vsplth":
            vd = int(ops[0][1:]); vb = int(ops[1][1:]); uimm = int(ops[2]) & 7
            return (f"{{ uint16_t* d=(uint16_t*)&ctx->vr[{vd}]; uint16_t* b=(uint16_t*)&ctx->vr[{vb}]; "
                    f"uint16_t v=b[{uimm}]; for(int i=0;i<8;i++) d[i]=v; }}")

        # Pack signed halfword signed saturate
        if mn == "vpkshss":
            vd, va, vb = int(ops[0][1:]), int(ops[1][1:]), int(ops[2][1:])
            return (f"{{ int8_t* d=(int8_t*)&ctx->vr[{vd}]; int16_t* a=(int16_t*)&ctx->vr[{va}]; "
                    f"int16_t* b=(int16_t*)&ctx->vr[{vb}]; "
                    f"for(int i=0;i<8;i++){{int32_t v=a[i]; d[i]=(int8_t)(v>127?127:v<-128?-128:v);}} "
                    f"for(int i=0;i<8;i++){{int32_t v=b[i]; d[8+i]=(int8_t)(v>127?127:v<-128?-128:v);}} }}")

        # vmsummbm (VA-form, 4 operands)
        if mn == "vmsummbm":
            vd = int(ops[0][1:]); va = int(ops[1][1:]); vb = int(ops[2][1:]); vc = int(ops[3][1:])
            return (f"{{ int32_t* d=(int32_t*)&ctx->vr[{vd}]; int8_t* a=(int8_t*)&ctx->vr[{va}]; "
                    f"uint8_t* ub=(uint8_t*)&ctx->vr[{vb}]; int32_t* cc=(int32_t*)&ctx->vr[{vc}]; "
                    f"for(int i=0;i<4;i++) d[i]=(int32_t)a[4*i]*(int32_t)ub[4*i]+(int32_t)a[4*i+1]*(int32_t)ub[4*i+1]"
                    f"+(int32_t)a[4*i+2]*(int32_t)ub[4*i+2]+(int32_t)a[4*i+3]*(int32_t)ub[4*i+3]+cc[i]; }}")

        # Merge high halfword / low halfword (vmrghh, vmrglh — already in vmrg* handler above)

        # ------- Default: emit as comment -------
        return f"/* TODO: {mn} {insn.operands} */;"

    def _branch_condition(self, mnemonic: str, ops: list[str]) -> str:
        """Generate a C condition expression for a conditional branch."""
        mn = mnemonic.rstrip("la")  # strip link and absolute bits
        if mn.startswith("b"):
            mn = mn[1:]  # strip leading 'b'

        # strip trailing 'lr', 'ctr'
        mn = mn.replace("lr", "").replace("ctr", "")

        cr_field = 0
        # Check if first operand is a CR field
        if ops and ops[0].startswith("cr"):
            try:
                cr_field = int(ops[0][2:])
            except ValueError:
                pass

        shift = (7 - cr_field) * 4

        cond_map = {
            "eq": f"((ctx->cr >> {shift}) & 2)",
            "ne": f"(!((ctx->cr >> {shift}) & 2))",
            "lt": f"((ctx->cr >> {shift}) & 8)",
            "ge": f"(!((ctx->cr >> {shift}) & 8))",
            "gt": f"((ctx->cr >> {shift}) & 4)",
            "le": f"(!((ctx->cr >> {shift}) & 4))",
            "so": f"((ctx->cr >> {shift}) & 1)",
            "ns": f"(!((ctx->cr >> {shift}) & 1))",
            "dnz": "((ctx->ctr = (uint32_t)(ctx->ctr - 1)) != 0)",
            "dz": "((ctx->ctr = (uint32_t)(ctx->ctr - 1)) == 0)",
        }

        return cond_map.get(mn, f"/* cond: {mnemonic} */ 1")

    # ------------------------------------------------------------------ #
    # Mid-function entry point resolution
    # ------------------------------------------------------------------ #

    def generate_mid_function_entries(self, all_insns: list[Instruction]) -> int:
        """Generate tail-entry functions for branch targets that land inside
        existing function bodies.

        When a trampoline or call references ``func_X`` and address X falls
        within [start, end) of an already-lifted function F, X is a
        mid-function entry point.  We generate a new function ``func_X``
        containing the lifted code from address X to F's end.

        Returns the number of tail-entry functions generated.
        """
        defined = {f.start_addr for f in self.functions}
        # All addresses that are referenced as func_X but not yet defined
        all_refs = (self.call_targets | self.branch_targets) - defined

        if not all_refs:
            return 0

        # Build an interval map: sorted list of (start, end) for existing funcs
        func_intervals = sorted((f.start_addr, f.end_addr) for f in self.functions)

        count = 0
        for target in sorted(all_refs):
            # Binary search: find the function whose range contains target
            container = None
            lo, hi = 0, len(func_intervals) - 1
            while lo <= hi:
                mid = (lo + hi) // 2
                fstart, fend = func_intervals[mid]
                if target < fstart:
                    hi = mid - 1
                elif target >= fend:
                    lo = mid + 1
                else:
                    # fstart <= target < fend, but skip if target == fstart
                    # (that's the function itself, already defined)
                    if target != fstart:
                        container = (fstart, fend)
                    break

            if container is None:
                continue

            fstart, fend = container
            # Lift the tail: from target to fend
            tail_func = self.lift_function(all_insns, target, fend)
            # lift_function already appends to self.functions, so it's included
            # in output. Update defined set so we don't re-generate.
            defined.add(target)
            count += 1

        return count

    # ------------------------------------------------------------------ #
    # Output generation
    # ------------------------------------------------------------------ #

    def emit_header(self) -> str:
        """Generate the C header file content."""
        lines = [HEADER_PREAMBLE]
        # Forward declarations
        for func in self.functions:
            lines.append(f"void {func.name}(ppu_context* ctx);")
        # Also declare any call/branch targets that aren't defined. Cross-
        # fragment branches (b/bc to an address outside the current function)
        # emit `func_XXXX` via the trampoline just like calls do, so external
        # branch targets need a prototype too -- not only call_targets.
        defined = {f.start_addr for f in self.functions}
        external = (self.call_targets | self.branch_targets) - defined
        for target in sorted(external):
            lines.append(f"void func_{target:08X}(ppu_context* ctx); /* external */")
        lines.append("")
        lines.append("/* Populate the runtime address->function map (defined in ppu_recomp.c). */")
        lines.append("#ifdef __cplusplus")
        lines.append('extern "C"')
        lines.append("#endif")
        lines.append("void ppu_recomp_register(void);")
        lines.append("")
        return "\n".join(lines)

    def emit_source(self) -> str:
        """Generate the C source file content."""
        lines = [SOURCE_PREAMBLE]

        # Emit helper macros
        lines.append("/* Rotate helpers */")
        lines.append("static inline uint32_t ppc_rlwinm(uint32_t rs, int sh, int mb, int me) {")
        lines.append("    uint32_t rotated = (rs << sh) | (rs >> (32 - sh));")
        lines.append("    uint32_t mask;")
        lines.append("    if (mb <= me) {")
        lines.append("        mask = ((uint32_t)-1 >> mb) & ((uint32_t)-1 << (31 - me));")
        lines.append("    } else {")
        lines.append("        mask = ((uint32_t)-1 >> mb) | ((uint32_t)-1 << (31 - me));")
        lines.append("    }")
        lines.append("    return rotated & mask;")
        lines.append("}")
        lines.append("")
        lines.append("static inline uint32_t ppc_rlwimi(uint32_t ra, uint32_t rs, int sh, int mb, int me) {")
        lines.append("    uint32_t rotated = (rs << sh) | (rs >> (32 - sh));")
        lines.append("    uint32_t mask;")
        lines.append("    if (mb <= me) {")
        lines.append("        mask = ((uint32_t)-1 >> mb) & ((uint32_t)-1 << (31 - me));")
        lines.append("    } else {")
        lines.append("        mask = ((uint32_t)-1 >> mb) | ((uint32_t)-1 << (31 - me));")
        lines.append("    }")
        lines.append("    return (rotated & mask) | (ra & ~mask);")
        lines.append("}")
        lines.append("")
        # 64-bit rotate helpers
        lines.append("/* 64-bit rotate helpers */")
        lines.append("static inline uint64_t ppc_rotl64(uint64_t v, int n) {")
        lines.append("    n &= 63;")
        lines.append("    return (v << n) | (v >> (64 - n));")
        lines.append("}")
        lines.append("static inline uint64_t ppc_mask64(int mb, int me) {")
        lines.append("    uint64_t mask;")
        lines.append("    if (mb <= me) {")
        lines.append("        mask = (mb == 0) ? ~0ULL : (~0ULL >> mb);")
        lines.append("        mask &= (me == 63) ? ~0ULL : (~0ULL << (63 - me));")
        lines.append("    } else {")
        lines.append("        mask = (~0ULL >> mb) | (~0ULL << (63 - me));")
        lines.append("    }")
        lines.append("    return mask;")
        lines.append("}")
        lines.append("static inline uint64_t ppc_rldicl(uint64_t rs, int sh, int mb) {")
        lines.append("    return ppc_rotl64(rs, sh) & ppc_mask64(mb, 63);")
        lines.append("}")
        lines.append("static inline uint64_t ppc_rldicr(uint64_t rs, int sh, int me) {")
        lines.append("    return ppc_rotl64(rs, sh) & ppc_mask64(0, me);")
        lines.append("}")
        lines.append("static inline uint64_t ppc_rldic(uint64_t rs, int sh, int mb) {")
        lines.append("    int me = 63 - sh;")
        lines.append("    return ppc_rotl64(rs, sh) & ppc_mask64(mb, me);")
        lines.append("}")
        lines.append("static inline uint64_t ppc_rldimi(uint64_t ra, uint64_t rs, int sh, int mb) {")
        lines.append("    int me = 63 - sh;")
        lines.append("    uint64_t mask = ppc_mask64(mb, me);")
        lines.append("    return (ppc_rotl64(rs, sh) & mask) | (ra & ~mask);")
        lines.append("}")
        lines.append("")

        # Build address-to-function map for fallthrough resolution
        func_by_addr = {f.start_addr: f for f in self.functions}
        sorted_addrs = sorted(func_by_addr.keys())

        import_map = getattr(self, "import_map", {})
        lines.append("//@@BODIES_START@@")
        for i, func in enumerate(self.functions):
            label = self.name_map.get(func.start_addr)
            if label:
                lines.append(f"/* {label} */")
            # A firmware import glink stub may be reached by tail-entry/branch
            # resolution and lifted with a real body (which reads the
            # unresolved import GOT and dispatches to garbage). Always emit the
            # HLE trampoline instead so both direct and indirect (function
            # pointer) calls reach the NID handler.
            if func.start_addr in import_map:
                nid = import_map[func.start_addr]
                # Replicate the glink's `std r2, 0x28(r1)`: it saves the
                # caller's TOC to the ABI slot so the caller's post-call
                # `ld r2, 0x28(r1)` restores the right TOC. Skipping it
                # corrupts r2 across import calls.
                lines.append(f"void {func.name}(ppu_context* ctx) "
                             f"{{ vm_write64(ctx->gpr[1] + 0x28, ctx->gpr[2]); "
                             f"ps3_hle_call(0x{nid:08X}u, ctx); }}  /* import glink */")
                lines.append("")
                continue
            lines.append(f"void {func.name}(ppu_context* ctx) {{")
            for bline in func.body_lines:
                lines.append(f"    {bline}" if not bline.endswith(":") else bline)

            # Check if this function needs a fallthrough call to the next function.
            # On PPC, if a function doesn't end with blr/b/bctr (a return or
            # unconditional branch), execution falls through to the next address.
            # The lifter may split one logical function into multiple pieces at
            # function boundary points, so we need to chain them.
            needs_fallthrough = True
            if func.body_lines:
                last_line = func.body_lines[-1].strip().rstrip(';')
                if (last_line.startswith('return') or
                    'goto ' in last_line or
                    last_line.startswith('func_') or
                    last_line.startswith('lv2_syscall') or
                    '{ func_' in last_line):
                    needs_fallthrough = False

            if needs_fallthrough:
                # Find the next function by address.
                # Use trampoline pattern to avoid deep call chains.
                try:
                    addr_idx = sorted_addrs.index(func.start_addr)
                    if addr_idx + 1 < len(sorted_addrs):
                        next_addr = sorted_addrs[addr_idx + 1]
                        next_func = func_by_addr[next_addr]
                        lines.append(f"        {{ g_trampoline_fn = (void(*)(void*)){next_func.name}; return; }}")
                except ValueError:
                    pass

            lines.append("}")
            lines.append("")

        lines.append("//@@BODIES_END@@")

        # Stubs for call targets not defined in this lift (subset/incremental
        # builds reference functions outside the lifted set). A full-image lift
        # has none. Stubs route through the runtime so an actual call to an
        # unlifted function is diagnosable rather than a silent no-op.
        undefined = sorted((self.call_targets | self.branch_targets)
                           - {f.start_addr for f in self.functions})
        import_map = getattr(self, "import_map", {})
        if undefined:
            lines.append("/* Call-target stubs: firmware imports route to the HLE NID")
            lines.append("   dispatch; the rest are unlifted (subset/incremental builds). */")
            lines.append('extern "C" void ppu_unlifted_stub(uint64_t addr, ppu_context* ctx);')
            lines.append('extern "C" void ps3_hle_call(unsigned int nid, ppu_context* ctx);')
            for target in undefined:
                if target in import_map:
                    nid = import_map[target]
                    lines.append(f"void func_{target:08X}(ppu_context* ctx) "
                                 f"{{ vm_write64(ctx->gpr[1] + 0x28, ctx->gpr[2]); "
                                 f"ps3_hle_call(0x{nid:08X}u, ctx); }}  /* import */")
                else:
                    lines.append(f"void func_{target:08X}(ppu_context* ctx) "
                                 f"{{ ppu_unlifted_stub(0x{target:08X}ULL, ctx); }}")
            lines.append("")

        # Function table
        lines.append("/* Function table */")
        lines.append("typedef struct { uint64_t addr; void (*func)(ppu_context*); const char* name; } func_entry;")
        lines.append(f"static const func_entry function_table[] = {{")
        for func in self.functions:
            lines.append(f'    {{ 0x{func.start_addr:08X}ULL, {func.name}, "{func.name}" }},')
        lines.append("    { 0, NULL, NULL }")
        lines.append("};")
        lines.append("")

        # Registration hook: the runtime loader provides ppu_register_function;
        # ppu_recomp_register() populates the address->function map used by
        # ps3_indirect_call and the entry dispatch. Call once at startup.
        lines.append('extern "C" void ppu_register_function(uint64_t addr, void (*fn)(ppu_context*));')
        lines.append('extern "C" void ppu_register_function(uint64_t addr, void (*fn)(ppu_context*));')
        lines.append('extern "C" void ppu_recomp_register(void) {')
        lines.append("    for (const func_entry* e = function_table; e->func; e++)")
        lines.append("        ppu_register_function(e->addr, e->func);")
        lines.append("}")
        lines.append("")

        self._source_lines = lines  # cached for emit_source_files()
        return "\n".join(l for l in lines if not l.startswith("//@@"))

    def emit_source_files(self, num_files: int):
        """Split the generated source across `num_files` C files so a large
        lift compiles as independent translation units (a single 14k-function
        file is ~88 MB -- impractical for one compiler invocation).

        Returns [(filename, content)]. Every file repeats the shared preamble
        (includes + static-inline helpers, harmless across TUs); the function
        table / registration / unlifted stubs go only in file 0. Cross-file
        calls resolve via the forward declarations in the header."""
        if not getattr(self, "_source_lines", None):
            self.emit_source()
        lines = self._source_lines
        si = lines.index("//@@BODIES_START@@")
        ei = lines.index("//@@BODIES_END@@")
        preamble = lines[:si]
        body = lines[si + 1:ei]
        tail = lines[ei + 1:]

        # Function-start boundaries within the body region.
        starts = [i for i, l in enumerate(body)
                  if l.startswith("void func_") and l.rstrip().endswith("{")]
        if not starts:
            return [(self.source_base + ".c", "\n".join(preamble + body + tail))]
        num_files = max(1, min(num_files, len(starts)))
        # Partition function-start indices into num_files contiguous groups.
        per = (len(starts) + num_files - 1) // num_files
        files = []
        for k in range(num_files):
            grp = starts[k * per:(k + 1) * per]
            if not grp:
                break
            lo = grp[0]
            hi = starts[(k + 1) * per] if (k + 1) * per < len(starts) else len(body)
            chunk = body[lo:hi]
            content = preamble + chunk + (tail if k == 0 else [])
            files.append((f"{self.source_base}_{k}.c",
                          "\n".join(l for l in content if not l.startswith("//@@"))))
        return files


