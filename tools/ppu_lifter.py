# CLI
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(description="PPU to C lifter for PS3 recompilation")
    parser.add_argument("input", help="Input ELF or raw binary")
    parser.add_argument("--output", "-o", default=".", help="Output directory")
    parser.add_argument("--header-name", default="ppu_recomp.h", help="Header file name")
    parser.add_argument("--source-name", default="ppu_recomp.c", help="Source file name")
    parser.add_argument("--raw", action="store_true", help="Treat input as raw binary")
    parser.add_argument("--base", type=lambda x: int(x, 0), default=0,
                        help="Base address (for raw binary)")
    parser.add_argument("--little-endian", action="store_true")
    parser.add_argument("--functions", metavar="FILE",
                        help="JSON file with function list [{start, end}, ...]")
    parser.add_argument("--names", metavar="FILE", default=None,
                        help="JSON name map from ghidra_names.py "
                             "({\"0xADDR\": {\"label\": ...}}); emitted as comments")
    parser.add_argument("--imports", metavar="FILE", default=None,
                        help="JSON firmware imports from ppu_loader.py "
                             "([{stub, nid}]); import stubs route to ps3_hle_call")
    parser.add_argument("--split-files", type=int, default=1, metavar="N",
                        help="split the source across N C files (for large "
                             "lifts; a single-file 14k-function lift is ~88 MB)")
    parser.add_argument("--toc", type=lambda x: int(x, 0), default=None,
                        help="module TOC (r2 base) for jump-table recovery; "
                             "auto-read from EBOOT.loader.json next to --functions")
    args = parser.parse_args()

    with open(args.input, "rb") as f:
        file_data = f.read()

    big_endian = not args.little_endian
    base_addr = args.base

    # Get instructions
    if args.raw:
        all_insns = disassemble_bytes(file_data, base_addr, big_endian)
    else:
        try:
            from elf_parser import ELFFile, PT_LOAD
            elf = ELFFile(args.input)
            elf.load()
            big_endian = elf.elf_header.big_endian
            all_insns = []
            for ph in elf.program_headers:
                if ph.p_type == PT_LOAD and (ph.p_flags & 1):
                    seg_data = elf.get_segment_data(elf.program_headers.index(ph))
                    all_insns.extend(disassemble_bytes(seg_data, ph.p_vaddr, big_endian))
            if not all_insns:
                for ph in elf.program_headers:
                    if ph.p_type == PT_LOAD and ph.p_filesz > 0:
                        seg_data = elf.get_segment_data(elf.program_headers.index(ph))
                        all_insns.extend(disassemble_bytes(seg_data, ph.p_vaddr, big_endian))
                        break
        except Exception as exc:
            print(f"Warning: ELF parse failed ({exc}), treating as raw", file=sys.stderr)
            all_insns = disassemble_bytes(file_data, base_addr, big_endian)

    # Get function boundaries
    if args.functions:
        with open(args.functions) as f:
            func_list = json.load(f)
        func_bounds = [(int(str(e["start"]), 0), int(str(e["end"]), 0)) for e in func_list]
    else:
        detected = detect_functions(all_insns)
        func_bounds = [(f["start"], f["end"]) for f in detected]

    if not func_bounds:
        print("No functions found. Use --functions to provide a function list.", file=sys.stderr)
        sys.exit(1)

    print(f"Lifting {len(func_bounds)} functions...")

    lifter = PPULifter()

    # Jump-table recovery needs (a) the module TOC and (b) word access to ALL
    # loadable segments (the table base pointer lives in the data segment, which
    # isn't in the executable-only `all_insns`).
    toc = args.toc
    if toc is None and args.functions:
        import os as _os
        ld = _os.path.join(_os.path.dirname(args.functions) or ".",
                           "EBOOT.loader.json")
        if _os.path.exists(ld):
            try:
                with open(ld) as lf:
                    toc = int(str(json.load(lf).get("module_toc", 0)), 0)
            except Exception:
                toc = None
    if toc:
        lifter.module_toc = toc
        import struct as _struct
        word_at = {}
        try:
            from elf_parser import ELFFile, PT_LOAD
            _elf = ELFFile(args.input); _elf.load()
            for ph in _elf.program_headers:
                if ph.p_type == PT_LOAD and ph.p_filesz > 0:
                    d = _elf.get_segment_data(_elf.program_headers.index(ph))
                    va = ph.p_vaddr
                    for off in range(0, len(d) - 3, 4):
                        word_at[va + off] = _struct.unpack_from(">I", d, off)[0]
        except Exception:
            word_at = {i.addr: i.raw for i in all_insns}
        lifter.word_at = word_at
        print(f"  Jump-table recovery enabled (TOC=0x{toc:08X}, "
              f"{len(word_at)} words)")

    # Optional: firmware import map (stub address -> NID). Import stubs are
    # emitted as HLE trampolines (ps3_hle_call) instead of unlifted stubs.
    lifter.import_map = {}
    if args.imports:
        with open(args.imports) as imf:
            for im in json.load(imf):
                lifter.import_map[int(str(im["stub"]), 0)] = int(str(im["nid"]), 0)
        print(f"  Loaded {len(lifter.import_map)} firmware import stubs")

    # Optional: load a recovered-name map (from Ghidra analysis) to annotate
    # generated functions with meaningful names as comments.
    if args.names:
        import json as _json
        with open(args.names) as nf:
            nm = _json.load(nf)
        loaded = 0
        for k, v in nm.items():
            try:
                addr = int(str(k), 16)
            except ValueError:
                continue
            label = v.get("label") if isinstance(v, dict) else str(v)
            if label:
                lifter.name_map[addr] = label
                loaded += 1
        print(f"  Loaded {loaded} recovered names from {args.names}")

    for start, end in func_bounds:
        lifter.lift_function(all_insns, start, end)

    # Resolve mid-function entry points: generate tail-entry functions for
    # branch/trampoline targets that land inside existing function bodies.
    # This runs iteratively because newly generated tail-entry functions may
    # themselves contain branches to other mid-function addresses.
    total_mid = 0
    max_passes = 10
    for pass_num in range(1, max_passes + 1):
        n = lifter.generate_mid_function_entries(all_insns)
        if n == 0:
            break
        total_mid += n
        print(f"  Mid-function pass {pass_num}: generated {n} tail-entry wrappers ({total_mid} total)")
    if total_mid:
        print(f"  Generated {total_mid} mid-function tail-entry wrappers total")

    os.makedirs(args.output, exist_ok=True)

    header_path = os.path.join(args.output, args.header_name)
    with open(header_path, "w") as f:
        f.write(lifter.emit_header())
    print(f"Wrote {header_path}")

    lifter.source_base = os.path.splitext(args.source_name)[0]
    if args.split_files > 1:
        lifter.emit_source()  # populate the cache
        for name, content in lifter.emit_source_files(args.split_files):
            p = os.path.join(args.output, name)
            with open(p, "w") as f:
                f.write(content)
            print(f"Wrote {p}")
    else:
        source_path = os.path.join(args.output, args.source_name)
        with open(source_path, "w") as f:
            f.write(lifter.emit_source())
        print(f"Wrote {source_path}")

    print(f"  {len(lifter.functions)} functions lifted")
    print(f"  {len(lifter.call_targets)} unique call targets")


if __name__ == "__main__":
    main()
