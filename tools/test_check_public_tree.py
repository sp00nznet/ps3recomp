#!/usr/bin/env python3
"""Synthetic tests for tools/check_public_tree.py; no game files involved."""
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_public_tree as guard  # noqa: E402


class FindingsTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)

    def check(self, name, data, policy=None):
        (self.root / name).parent.mkdir(parents=True, exist_ok=True)
        (self.root / name).write_bytes(data)
        return {reason for _, reason in guard.findings(self.root, [name], policy)}

    def test_clean_source_passes(self):
        self.assertEqual(self.check('src/a.cpp', b'int main() { return 0; }\n'), set())

    def test_game_file_types_and_binaries(self):
        self.assertIn('forbidden file type .elf', self.check('x/EBOOT.ELF', b'text'))
        self.assertIn('forbidden file type .sprx', self.check('x/m.sprx', b'text'))
        self.assertIn('binary content', self.check('x/blob.dat', b'\x7fELF\0\1'))
        self.assertIn('not UTF-8 text', self.check('x/latin.txt', b'caf\xe9\n'))

    def test_size_limit(self):
        policy = guard.Policy({'max_bytes': 16})
        self.assertIn('larger than 16 bytes', self.check('big.txt', b'a' * 17, policy))
        self.assertEqual(self.check('small.txt', b'a' * 16, policy), set())

    def test_derived_content(self):
        self.assertIn('generated-code header', self.check('a.cpp', b'/* Auto-generated by ppu_lifter.py */\n'))
        self.assertIn('generated-code header', self.check('b.c', b'/* Auto-generated by spu_lifter.py */\n'))
        self.assertIn('embedded byte image', self.check('c.c', b'const unsigned char i[]={' + b'0x7c, ' * 64 + b'};\n'))
        self.assertEqual(self.check('d.c', b'const unsigned char i[]={' + b'0x7c, ' * 8 + b'};\n'), set())
        self.assertIn('base64 blob', self.check('e.txt', b'QUJD' * 60 + b'\n'))
        listing = b''.join(b'  %05x: 7c0802a6 mflr r0\n' % (0x10000 + 4 * i) for i in range(5))
        self.assertIn('disassembly listing', self.check('f.txt', listing))
        self.assertEqual(self.check('g.txt', listing.split(b'\n', 1)[1]), set())  # four lines

    def test_machine_details(self):
        self.assertIn('absolute user path', self.check('a.py', b"p='/Users/someone/x'\n"))
        self.assertIn('absolute user path', self.check('b.c', b'char d[]="/private/tmp/x-XXXXXX";\n'))
        self.assertIn('absolute user path', self.check('c.bat', b'set P=C:\\Users\\someone\\game\n'))
        self.assertEqual(self.check('d.c', b'char d[]="/tmp/x-XXXXXX";\n'), set())

    def test_policy_tuning(self):
        policy = guard.Policy({'allow_suffixes': ['.PNG'], 'forbid_suffixes': ['.dat'],
                               'exclude': ['vendor/*'], 'patterns': {'chat link': r'chat\.example\.com/'}})
        self.assertEqual(self.check('icon.png', b'text', policy), set())
        self.assertIn('forbidden file type .dat', self.check('x.dat', b'text', policy))
        self.assertEqual(self.check('vendor/EBOOT.elf', b'text', policy), set())
        self.assertIn('chat link', self.check('n.md', b'see https://chat.example.com/x\n', policy))
        with self.assertRaises(ValueError):
            guard.Policy({'exclude_paths': []})


class CommandLineTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        subprocess.run(['git', 'init', '-q', str(self.root)], check=True)

    def add(self, name, data):
        (self.root / name).parent.mkdir(parents=True, exist_ok=True)
        (self.root / name).write_bytes(data)
        subprocess.run(['git', '-C', str(self.root), 'add', name], check=True)

    def test_only_tracked_files_are_checked_and_exit_status(self):
        self.add('src/main.cpp', b'int main() { return 0; }\n')
        (self.root / 'EBOOT.elf').write_bytes(b'untracked')
        self.assertEqual(guard.main(['--root', str(self.root)]), 0)
        self.add('game/EBOOT.elf', b'tracked')
        self.assertEqual(guard.main(['--root', str(self.root)]), 1)

    def test_default_config_file_is_read_and_not_flagged(self):
        self.add('public-tree.json', json.dumps({'patterns': {'chat link': r'chat\.example\.com/'},
                                                 'exclude': ['fixtures/*']}).encode())
        self.add('fixtures/EBOOT.elf', b'synthetic')
        self.assertEqual(guard.main(['--root', str(self.root)]), 0)
        self.add('notes.md', b'https://chat.example.com/abc\n')
        self.assertEqual(guard.main(['--root', str(self.root)]), 1)


if __name__ == '__main__':
    unittest.main()
