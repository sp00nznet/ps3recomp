#!/usr/bin/env python3
"""Refuse tracked files a game port must never publish.

A port repository should hold only its own source: never the game's files,
anything extracted, decrypted or lifted from them, or details of the machine it
was built on. This checker runs over `git ls-files` of a port repository and
reports every tracked file that looks like one of those:

- a file type that is a game image, container or build product (.elf, .self,
  .sprx, .pkg, .psarc, .edat, .o, ...);
- binary or non-UTF-8 content, or a file over the size limit;
- lifter output (the "Auto-generated by ppu_lifter/spu_lifter" header);
- an embedded byte image, a long base64 blob or a disassembly listing;
- an absolute path inside a user's home or the system temporary directory.

It exits 1 and lists every finding, so it can run in a port's CI.

A port tunes it with an optional JSON file (`--config`, default
`public-tree.json` at the checked root), for example:

    {"exclude": ["docs/screenshots/*.png"], "allow_suffixes": [".png"],
     "forbid_suffixes": [".dat"], "patterns": {"chat link": "chat\\.example\\.com/"},
     "max_bytes": 1000000}

`exclude` lists fnmatch globs that are never checked; `allow_suffixes` drops
suffixes from the default list and `forbid_suffixes` adds some; `patterns` adds
named regular expressions (for example a chat or session link format); and
`max_bytes` changes the size limit.
"""
import argparse
import fnmatch
import json
import re
import subprocess
import sys
from pathlib import Path

DEFAULT_MAX_BYTES = 1_000_000
CONFIG_NAME = 'public-tree.json'

# Game images and containers, then build products and captures.
DEFAULT_SUFFIXES = {
    '.bin', '.elf', '.self', '.sprx', '.prx', '.pkg', '.psarc', '.sdat', '.edat',
    '.rap', '.iso', '.pup',
    '.o', '.obj', '.a', '.lib', '.so', '.dylib', '.dll', '.exe',
    '.ppm', '.png', '.wav',
}

DEFAULT_PATTERNS = [
    ('absolute user path', rb'/Users/[A-Za-z]|/home/[a-z]|/private/(?:tmp|var)/|~/Documents'
                           rb'|[A-Za-z]:[\\/]+Users[\\/]+[A-Za-z]'),
    ('generated-code header', rb'Auto-generated by (?:ppu|spu)_lifter'),
    ('embedded byte image', rb'(?:0x[0-9a-fA-F]{2}\s*,\s*){64}'),
    ('base64 blob', rb'[A-Za-z0-9+/]{200,}={0,2}'),
    ('disassembly listing', rb'(?m)(?:^\s*(?:0x)?[0-9a-fA-F]{5,8}:?\s+(?:[0-9a-fA-F]{8}\s+)?'
                            rb'(?:lwz|stw|addi|bl|mflr|stwu|lqd|stqd|shufb|brsl|ori|rlwinm)\b.*\n){5}'),
]


class Policy:
    def __init__(self, config=None):
        config = config or {}
        unknown = set(config) - {'exclude', 'allow_suffixes', 'forbid_suffixes', 'patterns', 'max_bytes'}
        if unknown:
            raise ValueError(f'unknown public-tree config keys: {sorted(unknown)}')
        lower = lambda items: {s.lower() for s in items}
        self.exclude = list(config.get('exclude', []))
        self.suffixes = (DEFAULT_SUFFIXES - lower(config.get('allow_suffixes', []))) | lower(config.get('forbid_suffixes', []))
        self.max_bytes = int(config.get('max_bytes', DEFAULT_MAX_BYTES))
        self.patterns = [(name, re.compile(pattern)) for name, pattern in DEFAULT_PATTERNS]
        for name, pattern in config.get('patterns', {}).items():
            self.patterns.append((name, re.compile(pattern.encode())))

    def excluded(self, path):
        return any(fnmatch.fnmatchcase(path, glob) for glob in self.exclude)


def tracked(root):
    out = subprocess.run(['git', '-C', str(root), 'ls-files', '-z'],
                         check=True, capture_output=True).stdout
    return [p for p in out.decode('utf-8', 'surrogateescape').split('\0') if p]


def findings(root, paths, policy=None):
    policy = policy or Policy()
    for path in paths:
        if policy.excluded(path):
            continue
        file = Path(root) / path
        if not file.is_file():
            continue
        suffix = Path(path).suffix.lower()
        if suffix in policy.suffixes:
            yield path, f'forbidden file type {suffix}'
        data = file.read_bytes()
        if len(data) > policy.max_bytes:
            yield path, f'larger than {policy.max_bytes} bytes'
        if b'\0' in data:
            yield path, 'binary content'
            continue
        try:
            data.decode('utf-8')
        except UnicodeDecodeError:
            yield path, 'not UTF-8 text'
        for name, pattern in policy.patterns:
            if pattern.search(data):
                yield path, name


def load_policy(root, config_path):
    path = config_path or Path(root) / CONFIG_NAME
    if config_path is None and not path.is_file():
        return Policy()
    policy = Policy(json.loads(Path(path).read_text(encoding='utf-8')))
    if config_path is None:
        # The default config file names the patterns it looks for; never flag it.
        policy.exclude.append(CONFIG_NAME)
    return policy


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--root', type=Path, default=Path.cwd(),
                        help='port repository to check (default: current directory)')
    parser.add_argument('--config', type=Path,
                        help=f'policy JSON (default: {CONFIG_NAME} at the root, if present)')
    args = parser.parse_args(argv)
    policy = load_policy(args.root, args.config)
    problems = list(findings(args.root, tracked(args.root), policy))
    for path, reason in problems:
        print(f'{path}: {reason}')
    print(f'{len(problems)} finding(s)' if problems else 'public tree check passed')
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
