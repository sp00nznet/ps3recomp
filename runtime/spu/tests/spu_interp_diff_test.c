static const char* lname(int op, char* buf) { int i = 0; for (const char* s = r_name[op]; *s; s++) buf[i++] = (*s >= 'A' && *s <= 'Z') ? *s + 32 : *s; buf[i] = 0; return buf; }
static uint64_t g_rng = 0x9E3779B97F4A7C15ull;
static uint32_t rnd(void) { g_rng ^= g_rng << 13; g_rng ^= g_rng >> 7; g_rng ^= g_rng << 17; return (uint32_t)(g_rng >> 16); }
static uint64_t rnd64(void) { return (uint64_t)rnd() << 32 | rnd(); }

static uint32_t special_int(void) {
    static const uint32_t sp[] = { 0, ~0u, 0x80000000u, 0x7FFFFFFFu, 1, 0xFFFFu, 0x10000u, 0x8000u, 0xFFFF0000u, 0x7Fu, 0x80u, 0xFFu,
        0x01010101u, 0x80808080u, 0x7F7F7F7Fu, 0xFF00FF00u, 0x00FF00FFu, 0x7FFF7FFFu, 0x80008000u, 0x0000FFFFu };
    switch (rnd() & 3) {
    case 0: return sp[rnd() % (sizeof sp / sizeof sp[0])];
    case 1: return rnd() % 70;
    case 2: return (uint32_t)(0 - (rnd() % 70));
    default: return 1u << (rnd() & 31);
    }
}
static uint32_t int_word(void) {
    switch (rnd() & 3) {
    case 0: return rnd();
    case 1: return special_int();
    case 2: { static const uint8_t bs[] = {0,1,0x7F,0x80,0xFF}; uint32_t v = 0; for (int k = 0; k < 4; k++) v = v << 8 | bs[rnd() % 5]; return v; }
    default: return (rnd() & 0xFFFF) | (special_int() << 16);
    }
}
static uint32_t g_sweep;
static uint32_t float_word(void) {
    if ((rnd() & 7) == 0) { uint32_t w = (g_sweep++ & 0x1FFu) << 23 | (rnd() & 0x7FFFFF); return w; }   /* sweep every sign/exponent
    */
    uint32_t sgn = (rnd() & 1) ? 0x80000000u : 0;
    switch (rnd() % 16) {
    case 0: return sgn;                                             /* +-0 */
    case 1: return sgn | (1 + rnd() % 0x7FFFFF);                    /* denormal */
    case 2: return sgn | 0x7F800000u;                               /* +-inf (extended exp 255) */
    case 3: return sgn | 0x7F800000u | (rnd() & 0x7FFFFF);          /* NaN / extended */
    case 4: return sgn | 0x7F7FFFFFu;                               /* max normal */
    case 5: return sgn | 0x00800000u | ((rnd() & 3) ? 0 : (rnd() & 0x7FFFFF)); /* min normal */
    case 6: { static const uint32_t n[] = { 0x4F000000u, 0x4EFFFFFFu, 0x4F000001u, 0x4F800000u, 0x4F7FFFFFu, 0x4F800001u, 0x4F7FFFFEu, 0x3F800000u, 0x3F000000u, 0x40000000u, 0x7F000000u, 0x00FFFFFFu, 0x7EFFFFFFu };
              return sgn | n[rnd() % (sizeof n / sizeof n[0])]; }
    case 7: case 8: return rnd();                                   /* any bit pattern */
    case 9: return sgn | ((uint32_t)(1 + rnd() % 254) << 23) | (rnd() & 0x7FFFFF);  /* random normal */
    case 10: return sgn | ((uint32_t)(250 + rnd() % 6) << 23) | (rnd() & 0x7FFFFF); /* near-overflow */
    case 11: return sgn | ((uint32_t)(rnd() % 6) << 23) | (rnd() & 0x7FFFFF);       /* near-underflow */
    default: return sgn | ((uint32_t)(110 + rnd() % 31) << 23) | (rnd() & 0x7FFFFF); /* tame */
    }
}
static uint64_t double_word(void) {
    uint64_t sgn = (rnd() & 1) ? 1ull << 63 : 0, m = rnd64() & 0xFFFFFFFFFFFFFull;
    switch (rnd() % 14) {
    case 0: return sgn;
    case 1: return sgn | (m ? m : 1);                               /* denormal */
    case 2: return sgn | 0x7FF0000000000000ull;                     /* inf */
    case 3: return sgn | 0x7FF0000000000000ull | (m ? m : 1);      /* NaN (quiet or signalling) */
    case 4: return sgn | 0x7FEFFFFFFFFFFFFFull;                     /* max normal */
    case 5: return sgn | 0x0010000000000000ull;                     /* min normal */
    case 6: return sgn | 0x3FF0000000000000ull | (rnd() & 1 ? m : 0);
    case 7: return rnd64();
    case 8: return sgn | ((uint64_t)(1 + rnd() % 2046) << 52) | m;  /* random normal */
    case 9: return sgn | ((uint64_t)(2040 + rnd() % 7) << 52) | m;  /* near overflow */
    case 10: return sgn | ((uint64_t)(rnd() % 6) << 52) | m;        /* near underflow */
    default: return sgn | ((uint64_t)(1000 + rnd() % 48) << 52) | m; /* tame */
    }
}
/* operand class of an op: 0 integer, 1 single float, 2 double */
static int op_kind(int op) {
    switch (op) {
    case R_FA: case R_FS: case R_FM: case R_FMA: case R_FMS: case R_FNMS: case R_FCEQ: case R_FCGT: case R_FCMEQ: case R_FCMGT:
    case R_FREST: case R_FRSQEST: case R_FI: case R_CFLTS: case R_CFLTU: case R_FESD: return 1;
    case R_DFA: case R_DFS: case R_DFM: case R_DFMA: case R_DFMS: case R_DFNMS: case R_DFNMA: case R_DFCEQ: case R_DFCGT:
    case R_DFCMEQ: case R_DFCMGT: case R_DFTSV: case R_FRDS: return 2;
    }
    return 0;
}

