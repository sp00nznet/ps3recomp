static uint8_t g_ls0[0x40000];     /* pristine LS (never holds the test instruction) */

static void bsw_store(uint8_t* o, const u128* v) { for (int i = 0; i < 4; i++) { uint32_t w = v->_u32[i]; o[4*i] = w >> 24; o[4*i+1] = w >> 16; o[4*i+2] = w >> 8; o[4*i+3] = w; } }
static void set_reg(int r, uint32_t w0, uint32_t w1, uint32_t w2, uint32_t w3) {
    g_orig[r]._u32[0] = w0; g_orig[r]._u32[1] = w1; g_orig[r]._u32[2] = w2; g_orig[r]._u32[3] = w3; bsw_store(g_gbe[r], &g_orig[r]);
}
static void fill_reg(int r, int kind) {
    uint32_t w[4];
    if (kind == 0) for (int i = 0; i < 4; i++) w[i] = int_word();
    else if (kind == 1) for (int i = 0; i < 4; i++) w[i] = float_word();
    else { for (int i = 0; i < 2; i++) { uint64_t d = double_word(); w[2*i] = (uint32_t)(d >> 32); w[2*i+1] = (uint32_t)d; } }
    set_reg(r, w[0], w[1], w[2], w[3]);
}

