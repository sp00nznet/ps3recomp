static int run_lifted_cases(long scale) {
    OpStat all; memset(&all, 0, sizeof all); int failing = 0;
    int cur_op = -1; OpStat st; int printed = 0; char nm[32] = "";
    for (long ci = 0; ci <= LC_NCASES; ci++) {
        int op = ci < LC_NCASES ? ref_decode(g_lc_cases[ci].insn) : -2;
        if (op != cur_op) {
            if (cur_op > 0) { g_ops_done++; g_total_trials += st.trials; g_total_fail += st.fail; g_total_skip += st.skipped_oracle; g_total_hand += st.hand_fallback;
                printf("%-9s %-10s %9ld lifted trials  %ld mismatches\n", st.fail ? "FAIL" : "ok", nm, st.trials, st.fail); failing += st.fail != 0; }
            memset(&st, 0, sizeof st); printed = 0; cur_op = op; if (op > 0) lname(op, nm);
        }
        if (ci == LC_NCASES) break;
        uint32_t insn = g_lc_cases[ci].insn, pc = g_lc_cases[ci].pc; int kind = op_kind(op);
        for (long t = 0; t < 24 * scale * (kind ? 3 : 1); t++) {
            int ra = (insn >> 7) & 0x7F, rb = (insn >> 14) & 0x7F, rt = insn & 0x7F, rt4 = (insn >> 21) & 0x7F;
            int regs[4] = { ra, rb, rt, rt4 };
            for (int i = 0; i < 4; i++) fill_reg(regs[i], (op == R_CSFLT || op == R_CUFLT) ? 0 : kind);
            for (int i = 0; i < 3; i++) if ((rnd() & 3) == 0) fill_reg(ALIAS_REG[i], kind);
            if ((rnd() & 7) == 0) { memcpy(&g_orig[rb], &g_orig[ra], 16); if (rnd() & 1) g_orig[rb]._u8[rnd() & 15] ^= (uint8_t)(1 + rnd() % 255); bsw_store(g_gbe[rb], &g_orig[rb]); }
            one_trial(op, insn, pc, backend_lifted, (void*)ci, &st, &printed, nm);
        }
    }
    return failing;
}
