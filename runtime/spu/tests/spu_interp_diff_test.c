/* instruction construction                                                                 */
/* ======================================================================================== */
enum { F_NONE, F_I7, F_I8, F_I10, F_I16, F_I18 };
static int op_magn(int op) { for (int i = 0; i < R_NTAB; i++) if (r_tab[i].op == op) return r_tab[i].magn; return -1; }
static int op_imm_kind(int op) {
    switch (op) {
    case R_ROTI: case R_ROTMI: case R_ROTMAI: case R_SHLI: case R_ROTHI: case R_ROTHMI: case R_ROTMAHI: case R_SHLHI:
    case R_CBD: case R_CHD: case R_CWD: case R_CDD: case R_ROTQBII: case R_ROTQMBII: case R_SHLQBII: case R_ROTQBYI: case R_ROTQMBYI: case R_SHLQBYI:
        return F_I7;
    }
    switch (op_magn(op)) { case 1: return F_I8; case 2: return F_I16; case 3: return F_I10; case 4: return F_I18; }
    return F_NONE;
}
static int op_is_rrr(int op) { return op_magn(op) == 7; }
static uint32_t op_prefix_insn(int op) {
    for (int i = 0; i < R_NTAB; i++) if (r_tab[i].op == op) { int pbits = 11 - r_tab[i].magn; return r_tab[i].val << (32 - pbits); }
    return 0;
}
static int imm_bits(int k) { return k == F_I7 ? 7 : k == F_I8 ? 8 : k == F_I10 ? 10 : k == F_I16 ? 16 : k == F_I18 ? 18 : 0; }
static int imm_shift(int k) { return (k == F_I16 || k == F_I18) ? 7 : 14; }
#define NPAT_ALIAS 81
#define NPAT_TOTAL (NPAT_ALIAS + 30)
/* regs used by alias patterns */
static const int ALIAS_REG[3] = { 5, 6, 7 };

static uint32_t build_insn(int op, int pat, uint32_t imm, int* used_regs /*[4]: rt ra rb rc, -1 unused*/) {
    int k = op_imm_kind(op), rrr = op_is_rrr(op);
    uint32_t insn = op_prefix_insn(op);
    int f[4];   /* rt, ra, rb, rc(=rt4 dest in RRR) */
    if (pat < NPAT_ALIAS) { int p = pat; for (int i = 0; i < 4; i++) { f[i] = ALIAS_REG[p % 3]; p /= 3; } }
    else for (int i = 0; i < 4; i++) { f[i] = (int)(rnd() % 128); if (f[i] == 1) f[i] = 2; }   /* r1: RPCS3's CBX family asserts on a misaligned SP */
    for (int i = 0; i < 4; i++) used_regs[i] = -1;
    /* low bits not otherwise assigned stay random */
    uint32_t rest = rnd();
    int lo_bits_top;                          /* bits below the opcode prefix */
    { int pbits = 11 - op_magn(op); lo_bits_top = 32 - pbits; }
    uint32_t lowmask = (lo_bits_top >= 32) ? ~0u : ((1u << lo_bits_top) - 1);
    insn |= rest & lowmask;
    if (rrr) {
        insn = (insn & ~(0x7Fu << 21)) | ((uint32_t)f[0] << 21); used_regs[0] = f[0];
        insn = (insn & ~(0x7Fu << 7))  | ((uint32_t)f[1] << 7);  used_regs[1] = f[1];
        insn = (insn & ~(0x7Fu << 14)) | ((uint32_t)f[2] << 14); used_regs[2] = f[2];
        insn = (insn & ~0x7Fu)         | (uint32_t)f[3];         used_regs[3] = f[3];
    } else {
        insn = (insn & ~0x7Fu) | (uint32_t)f[0]; used_regs[0] = f[0];
        if (k != F_I16 && k != F_I18) { insn = (insn & ~(0x7Fu << 7)) | ((uint32_t)f[1] << 7); used_regs[1] = f[1]; }
        if (k == F_NONE) { insn = (insn & ~(0x7Fu << 14)) | ((uint32_t)f[2] << 14); used_regs[2] = f[2]; }
        if (k != F_NONE) { int b = imm_bits(k), s = imm_shift(k); uint32_t m = ((1u << b) - 1) << s; insn = (insn & ~m) | ((imm << s) & m); }
    }
    switch (op) { case R_BI: case R_BISL: case R_IRET: case R_BISLED: case R_BIZ: case R_BINZ: case R_BIHZ: case R_BIHNZ: case R_HBR:
        if ((insn & (3u << 18)) == (3u << 18)) insn &= ~(1u << 19);   /* e&&d is architecturally undefined (RPCS3 throws) */ break; default: break; }
    if (op == R_RDCH || op == R_WRCH || op == R_RCHCNT) { used_regs[1] = -1; insn = (insn & ~(0x7Fu << 7)) | ((rnd() % 128) << 7); }
    return insn;
}

