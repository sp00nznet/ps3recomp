/* spu_interp_diff_test.c -- bit-exact differential test of the SPU interpreter (and, optionally,
 * the SPU lifter's emitted C) against RPCS3's own SPU interpreter.
 *
 * ORACLE: rpcs3_oracle/ compiles rpcs3/rpcs3/Emu/Cell/SPUInterpreter.cpp's per-instruction
 * functions unmodified (see rpcs3_oracle/extract.py) against a stub spu_thread, decoded with
 * RPCS3's own spu_decoder. Integer/logical/shift/shuffle/memory/branch/channel ops and
 * FREST/FRSQEST/FI are RPCS3's live ("fast") interpreter functions; the floating-point
 * arithmetic/compare/convert and double-precision ops are RPCS3's spu_interpreter_precise::*
 * implementations (the exact-semantics float path: round-toward-zero, denormal flush, extended
 * range). That block is `#if 0` dead code in this RPCS3 snapshot; extract.py enables it.
 * FI is a port of the SPU LLVM recompiler's spu_fi intrinsic (the interpreter's FI is a TODO).
 * Ops RPCS3 does not implement (dfceq/dfcgt/dfcmeq/dfcmgt) fall back to the hand-written ISA
 * reference below (ref_exec); so does dftsv (RPCS3 stubs it as fatal), checked against the Cell SPU ISA.
 * --audit compares that hand-written reference with RPCS3 itself (they agree on every integer op;
 * they differ on float/double, where the hand reference is plain IEEE).
 * Known RPCS3 precise-path quirk compensated for: CSFLT/CUFLT of a zero lane with i8 > 155 returns
 * a nonzero float there; the test expects 0 (see one_trial).
 *
 * Coverage: for every opcode, ALL values of every immediate field (i7/i8/i10/i16/i18), 81
 * rt/ra/rb/rc aliasing patterns (3^4 over three registers) plus fully random register fields,
 * and random + special-valued operands (ints: 0,-1,0x80000000,0x7FFFFFFF,byte patterns; floats:
 * +-0, denormals, +-inf, NaN, max/min normal, extended range, values around 2^31/2^32).
 * Compared bit-exactly: all 128 registers, the quadword touched in LS, next pc, halt/stop state,
 * channel number/operand routing.
 *
 * LIFTED MODE: build_diff_test.sh samples instruction words (--emit-cases), lifts each with
 * tools/spu_lifter.py (gen_lifted_cases.py), compiles the emitted C into a second binary and runs
 * it against the same oracle (`spu_lifted_diff_test --lifted`).
 *
 * Build/run:  ./build_diff_test.sh [--run [-- args]]     (needs the local rpcs3 tree, RPCS3_SRC=...)
 *   build_diff/spu_interp_diff_test [scale] [seed] [--audit] [--op NAME]   interpreter vs RPCS3
 *   build_diff/spu_lifted_diff_test --lifted [scale] [seed]                 lifted C vs RPCS3
 *   CASE_SCALE=N ./build_diff_test.sh   more lifted instruction words per op (default ~21K cases)
 */
