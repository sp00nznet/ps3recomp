/* ---- decode cross-check ---- */
static long decode_check(void) {
    long bad = 0, n = 0; spu_ins d;
    for (uint32_t p = 0; p < 2048; p++) for (int k = 0; k < 64; k++) {
        uint32_t insn = (p << 21) | (rnd() & 0x1FFFFF);
        if (k == 0) insn = p << 21;
        if (k == 1) insn = (p << 21) | 0x1FFFFF;
        spu_decode1(insn, 0, &d); n++;
        int rop = ref_decode(insn); const char* have = d.op == SPU_word ? "?" : spu_op_name[d.op]; char nm[32]; lname(rop, nm);
        int match = (rop == R_UNK) ? (d.op == SPU_word) : (d.op != SPU_word && !strcmp(have, nm));
        if (!match) { if (bad < 12) printf("  DECODE %08X: interp '%s' ref '%s'\n", insn, have, rop == R_UNK ? "?" : nm); bad++; }
    }
    for (long i = 0; i < 2000000; i++) { uint32_t insn = rnd() ^ (rnd() << 16); spu_decode1(insn, 0, &d); n++;
        int rop = ref_decode(insn); const char* have = d.op == SPU_word ? "?" : spu_op_name[d.op]; char nm[32]; lname(rop, nm);
        int match = (rop == R_UNK) ? (d.op == SPU_word) : (d.op != SPU_word && !strcmp(have, nm));
        if (!match) { if (bad < 12) printf("  DECODE %08X: interp '%s' ref '%s'\n", insn, have, rop == R_UNK ? "?" : nm); bad++; } }
    printf("decode cross-check vs RPCS3 opcode table: %ld words, %ld mismatches\n", n, bad);
    return bad;
}

/* Deterministic sample of instruction words for lifted mode: every op, alias patterns, boundary + random immediates. */
static void emit_cases(long scale) {
    for (int op = 1; op < R_COUNT; op++) {
        if (op_magn(op) < 0) continue;
        int k = op_imm_kind(op), used[4];
        long n = k == F_NONE ? NPAT_TOTAL : 100 * scale;
        for (long c = 0; c < n; c++) {
            uint32_t imm = 0;
            if (k != F_NONE) {
                int b = imm_bits(k); uint32_t mask = (1u << b) - 1, h = 1u << (b - 1);
                static const uint32_t sp[] = { 0, 1, 2, 3, 4, 7, 8, 15, 16, 31, 32, 63, 64, 127, 128, 255, 256, 511, 512, 1023 };
                if (c < 24) { uint32_t q = c % 12; imm = q < 4 ? q : q < 8 ? mask - (q - 4) : q == 8 ? h : q == 9 ? h - 1 : q == 10 ? h + 1 : mask >> 1; if (c >= 12) imm = sp[c % 20]; }
                else imm = rnd();
                imm &= mask;
            }
            int pat = (int)(c % NPAT_TOTAL);
            uint32_t insn = build_insn(op, pat, imm, used);
            switch (op) { case R_BI: case R_BISL: case R_IRET: case R_BISLED: case R_BIZ: case R_BINZ: case R_BIHZ: case R_BIHNZ:
                if (((insn >> 7) & 0x7F) == 0) insn |= 2u << 7; break; default: break; }   /* bi $r0 is the lifter's function-return idiom, not a plain jump */
            uint32_t pc = (rnd() % 8 == 0) ? ((rnd() & 1) ? 0x3FFFC : 0) : (rnd() & 0x3FFFC);
            /* skip direct branches to themselves (the lifter turns them into goto/halt idioms) */
            { int16_t i16 = (int16_t)((insn >> 7) & 0xFFFF); uint32_t t = 0xFFFFFFFFu;
              if (op == R_BR || op == R_BRSL || op == R_BRZ || op == R_BRNZ || op == R_BRHZ || op == R_BRHNZ) t = (pc + (uint32_t)(i16 * 4)) & 0x3FFFC;
              if (op == R_BRA || op == R_BRASL) t = (uint32_t)(i16 * 4) & 0x3FFFC;
              if (t == pc) continue; }
            printf("%08X %05X\n", insn, pc);
        }
    }
}

int main(int argc, char** argv) {
    long scale = 1; const char* only = 0; int npos = 0, emit = 0, lifted = 0;
    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--audit")) g_audit = 1;
        else if (!strcmp(argv[i], "--emit-cases")) emit = 1;
        else if (!strcmp(argv[i], "--lifted")) lifted = 1;
        else if (!strcmp(argv[i], "--op") && i + 1 < argc) only = argv[++i];
        else if (argv[i][0] != '-') { if (!npos++) scale = atol(argv[i]); else g_rng ^= (uint64_t)atoll(argv[i]) * 0x2545F4914F6CDD1Dull; }
    }
    if (emit) { emit_cases(scale); return 0; }
    spu_context_init(&g_ctx, 0);
    for (int i = 0; i < 0x40000; i++) g_ctx.ls[i] = (uint8_t)rnd();
    memcpy(g_ls0, g_ctx.ls, sizeof g_ls0);
    rpcs3_oracle_set_ls(g_ls0);
    for (int r = 0; r < 128; r++) fill_reg(r, 0);
    long dbad = (g_audit || lifted) ? 0 : decode_check();
    int failing = 0;
#ifdef LIFTED_CASES_INC
    if (lifted) {
        freopen("/dev/null", "w", stderr);   /* the lifter's halt-assert traces */
        failing += run_lifted_cases(scale);
        if (memcmp(g_ctx.ls, g_ls0, sizeof g_ls0)) { printf("LS corrupted\n"); g_total_fail++; }
        printf("lifted cases: %d  trials: %ld  mismatches: %ld\n", LC_NCASES, g_total_trials, g_total_fail);
        printf("RPCS3 undefined/unimplemented trials: %ld (compared to the hand-written ISA reference instead: %s; not compared at all: %s)\n", g_total_skip, g_hand_ops, g_skip_ops);
        printf("spu_lifted_diff_test: %s\n", g_total_fail ? "FAIL" : "PASS");
        return g_total_fail ? 1 : 0;
    }
#endif
    if (lifted) { printf("built without lifted cases (see build_diff_test.sh --lifted)\n"); return 2; }
    for (int op = 1; op < R_COUNT; op++) {
        char nm[32]; lname(op, nm);
        if (only && strcmp(only, nm)) continue;
        if (op_magn(op) < 0) continue;
        failing += run_op(op, scale, backend_interp, 0);
        if ((op & 7) == 0) for (int r = 0; r < 128; r++) fill_reg(r, 0);
        if (memcmp(g_ctx.ls, g_ls0, sizeof g_ls0)) { printf("LS corrupted after %s\n", nm); memcpy(g_ctx.ls, g_ls0, sizeof g_ls0); g_total_fail++; }
    }
    printf("ops: %d  trials: %ld  mismatches: %ld  decode mismatches: %ld\n", g_ops_done, g_total_trials, g_total_fail, dbad);
    printf("RPCS3 undefined/unimplemented trials: %ld (compared to the hand-written ISA reference instead: %s; not compared at all: %s)\n", g_total_skip, g_hand_ops, g_skip_ops);
    int okk = !g_total_fail && !dbad;
    printf("spu_interp_diff_test%s: %s\n", g_audit ? " (audit hand-ref vs RPCS3)" : "", okk ? "PASS" : "FAIL");
    return okk ? 0 : 1;
}
